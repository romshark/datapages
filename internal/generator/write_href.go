// WritePkgHref generates code for the datapagesgen/href package and appends it to buffer.
func (w *Writer) WritePkgHref(m *model.App) {
	needsStrconv, needsStrings, needsText := false, false, false
	for _, p := range m.Pages {
		if p.PageSpecialization == model.PageTypeError500 {
			continue
		}
		if p.GET == nil {
			continue
		}
		pathVars := slices.Collect(routepattern.Vars(p.Route))
		if len(pathVars) > 0 {
			needsStrings = true
			// Check for non-string path fields.
			if p.GET.Handler != nil && p.GET.InputPath != nil {
				fields := w.structFields(p.GET.InputPath.Type.Resolved)
				if hasNonStringFields(fields) {
					needsStrconv = true
				}
				if hasTextMarshalerFields(fields) {
					needsText = true
				}
			}
		}
		if p.GET.Handler != nil && p.GET.InputQuery != nil {
			needsStrings = true
			fields := w.structFields(p.GET.InputQuery.Type.Resolved)
			if hasNonStringFields(fields) {
				needsStrconv = true
			}
			if hasTextMarshalerFields(fields) {
				needsText = true
			}
		}
	}

	w.writeHrefHeader(needsStrconv, needsStrings)
	if needsText {
		w.writeTextOf()
	}
	w.writeHrefExternal()
	w.writeHrefAsset()

	for _, p := range m.Pages {
		if p.PageSpecialization == model.PageTypeError500 {
			continue
		}
		if p.GET == nil {
			continue
		}
		w.writeHrefFunc(p)
	}
}

func (w *Writer) writeHrefHeader(needsStrconv, needsStrings bool) {
	w.Line(0, "// Code generated by github.com/romshark/datapages; DO NOT EDIT.")
	w.Line(0, "")
	w.Line(0, "// Package href provides generators for datastar anchor hypertext references.")
	w.Line(0, "// Use these in templates instead of hardcoding URLs.")
	w.Line(0, "package href")
	w.Line(0, "")

	// Always need log/slog and sync for SetLogger/External.
	w.Line(0, "import (")
	w.Line(1, `"log/slog"`)
	if w.assetsURLPrefix != "" {
		w.Line(1, `"path"`)
	}
	if needsStrconv {
		w.Line(1, `"strconv"`)
	}
	if needsStrings {
		w.Line(1, `"net/url"`)
	}
	if needsStrings || w.assetsURLPrefix != "" {
		w.Line(1, `"strings"`)
	}
	w.Line(1, `"sync/atomic"`)
	w.Line(0, "")
	w.Line(1, `"github.com/romshark/datapages/runtime/hrefcheck"`)
	w.Line(0, ")")
}

// writeTextOf writes the helper that renders a value that marshals itself.
//
// It is generated per package rather than imported from the runtime,
// since the action package imports nothing that could hold it.
func (w *Writer) writeTextOf() {
	w.Line(0, "")
	w.Line(0, "// textOf is what v marshals to. A builder returns no error,")
	w.Line(0, "// hence a failing MarshalText falls back to fmt.Sprint.")
	w.Line(0, "func textOf(v encoding.TextMarshaler) string {")
	w.Line(1, "b, err := v.MarshalText()")
	w.Line(1, "if err != nil {")
	w.Line(2, "return fmt.Sprint(v)")
	w.Line(1, "}")
	w.Line(1, "return string(b)")
	w.Line(0, "}")
}

func (w *Writer) writeHrefExternal() {
	w.Line(0, "")
	w.Line(0, "var logger atomic.Pointer[slog.Logger]")
	w.Line(0, "")
	w.Line(0, "func init() { logger.Store(slog.Default()) }")
	w.Line(0, "")
	w.Line(0, "// SetLogger sets the logger used by External to log invalid URLs.")
	w.Line(0, "// Passing nil resets to the default logger. It is safe for concurrent use.")
	w.Line(0, "func SetLogger(l *slog.Logger) {")
	w.Line(1, "if l == nil {")
	w.Line(2, "l = slog.Default()")
	w.Line(1, "}")
	w.Line(1, "logger.Store(l)")
	w.Line(0, "}")
	w.Line(0, "")
	w.Line(0, "func getLogger() *slog.Logger { return logger.Load() }")
	w.Line(0, "")
	w.Line(0, "// External returns url as-is for use in href attributes.")
	w.Line(0, "// It warns about a URL that belongs in a generated builder,")
	w.Line(0, "// and about one the templ sanitizer drops.")
	w.Linef(0, "func External(url string) string {")
	if w.assetsURLPrefix != "" {
		w.Linef(1, `switch {`)
		w.Linef(1, `case !hrefcheck.IsAllowedNonRelativeHref(url) && !strings.HasPrefix(url, %q):`, w.assetsURLPrefix)
	} else {
		w.Line(1, `switch {`)
		w.Line(1, `case !hrefcheck.IsAllowedNonRelativeHref(url):`)
	}
	w.Line(2, `getLogger().Warn("href.External called with app-internal URL", "url", url)`)
	w.Line(1, `case !hrefcheck.IsRenderedAsWritten(url):`)
	w.Line(2, `getLogger().Warn("href.External called with a URL the templ sanitizer drops, "+`)
	w.Line(3, `"which renders it as about:invalid", "url", url)`)
	w.Line(1, "}")
	w.Line(1, "return url")
	w.Line(0, "}")
}

func (w *Writer) writeHrefAsset() {
	if w.assetsURLPrefix == "" {
		return
	}
	w.Line(0, "")
	w.Line(0, "// Asset returns the URL path for a static asset file.")
	w.Linef(0, `// For example, Asset("style.css") returns %q.`, w.assetsURLPrefix+"style.css")
	w.Line(0, "func Asset(p string) string {")
	w.Linef(1, "return hrefcheck.AssetPath(%q, p)", w.assetsURLPrefix)
	w.Line(0, "}")
}

// writeRouteComment writes a doc comment line like "// FuncName references /route/{$}\n".
// It ensures the route ends with {$} for exact matching display.
func (w *Writer) writeRouteComment(funcName, route string) {
	w.Raw("// ")
	w.Raw(funcName)
	w.Raw(" references ")
	if strings.HasSuffix(route, "{$}") {
		w.Raw(route)
	} else if route == "/" {
		w.Raw("/{$}")
	} else {
		w.Raw(route)
		w.Raw("/{$}")
	}
	w.Byte('\n')
}

func (w *Writer) writeHrefFunc(p *model.Page) {
	funcName := p.TypeName
	pathVars := slices.Collect(routepattern.Vars(p.Route))
	hasPathVars := len(pathVars) > 0

	// Build typed path param info.
	var pathInput *model.Input
	if p.GET != nil && p.GET.Handler != nil {
		pathInput = p.GET.InputPath
	}
	params := w.pathParamInfos(pathInput, pathVars)

	var querySt *types.Struct
	var queryFields []structFieldInfo
	if p.GET != nil && p.GET.Handler != nil && p.GET.InputQuery != nil {
		if st, ok := p.GET.InputQuery.Type.Resolved.Underlying().(*types.Struct); ok {
			querySt = st
			queryFields = w.structFields(querySt)
		}
	}
	hasQuery := len(queryFields) > 0

	// Doc comment.
	w.Line(0, "")
	w.writeRouteComment(funcName, p.Route)

	if !hasPathVars && !hasQuery {
		// Simple one-liner.
		w.Raw("func ")
		w.Raw(funcName)
		w.Raw("() string { return \"")
		w.Raw(routepattern.WithTrailingSlash(p.Route))
		w.Raw("\" }\n")
		return
	}

	// Build function signature.
	if hasPathVars && !hasQuery {
		// Path-only function.
		w.writeHrefFuncPathOnly(funcName, p.Route, params)
	} else if !hasPathVars && hasQuery {
		// Query-only function.
		w.writeHrefFuncQueryOnly(funcName, p.Route, queryFields)
		w.writeHrefQueryType(funcName, querySt)
	} else {
		// Both path and query params.
		w.writeHrefFuncPathAndQuery(funcName, p.Route, params, queryFields)
		w.writeHrefQueryType(funcName, querySt)
	}
}

func (w *Writer) writeHrefFuncPathOnly(funcName, route string, params []pathParamInfo) {
	// Function signature with path params.
	w.Raw("func ")
	w.Raw(funcName)
	w.Byte('(')
	w.writeTypedParams(params)
	w.Raw(") string {\n")

	// Pre-convert non-string params to strings.
	w.writePathPreConvert(params)

	literals, _ := routepattern.Segments(route)
	// The model may be partial: cmd/gen hands the generator what parsed so an
	// IDE can still resolve the import, and a route the parser rejected can
	// still reach here. Indexing params[i-1] below would panic on it.
	if len(literals) != len(params)+1 {
		w.Line(1, `return ""`)
		w.Line(0, "}")
		return
	}
	lo := newHrefLocals(params, nil)

	// Builder.
	w.Linef(1, "var %s strings.Builder", lo.builder)
	w.Linef(1, "%s.Grow(", lo.builder)
	for i, lit := range literals {
		if i == 0 {
			w.Linef(2, "len(%q) +", lit)
		} else if i < len(literals)-1 {
			w.Linef(3, "len(%s) +", pathVarStrExpr(params[i-1]))
			w.Linef(3, "len(%q) +", lit)
		} else {
			w.Linef(3, "len(%s) +", pathVarStrExpr(params[i-1]))
			w.Linef(3, "len(%q),", lit)
		}
	}
	w.Line(1, ")")

	// Write segments.
	for i, lit := range literals {
		w.Linef(1, "%s.WriteString(%q)", lo.builder, lit)
		if i < len(params) {
			w.Linef(1, "%s.WriteString(%s)", lo.builder, pathVarStrExpr(params[i]))
		}
	}

	w.Linef(1, "return %s.String()", lo.builder)
	w.Line(0, "}")
}

func (w *Writer) writeHrefFuncQueryOnly(
	funcName, route string, fields []structFieldInfo,
) {
	w.Linef(0, "func %s(query Query%s) string {", funcName, funcName)
	lo := newHrefLocals(nil, fields)

	// Pre-convert non-string fields to strings.
	w.writeQueryPreConvert(lo, fields)

	// anyQuery check.
	w.writeAnyCheck(lo.anyQuery, fields)
	w.Line(0, "")

	// Length calculation.
	w.Line(1, "var b strings.Builder")
	w.Raw("\tl := len(\"")
	w.Raw(routepattern.WithTrailingSlash(route))
	w.Raw("\")\n")
	w.Line(1, "if anyQuery {")
	w.Line(2, `l += len("?")`)
	w.Line(1, "}")
	w.Line(0, "")

	// n counter for & separator.
	w.Line(1, `// n = number of query params already accounted for (for '&')`)
	w.Line(1, "n := 0")
	w.Line(0, "")

	for _, f := range fields {
		tag := structtag.QueryTagValue(f.Tag)
		w.writeIfZeroCheck(1, "query."+f.Name, f.Type)
		w.Line(2, "if n > 0 {")
		w.Line(3, `l += len("&")`)
		w.Line(2, "}")
		w.Line(2, "n++")
		w.Linef(2, "%s += len(%q) + len(%s)", lo.length, tag+"=", lo.queryStr[tag])
		w.Line(1, "}")
	}
	w.Line(1, "_ = n")
	w.Line(0, "")

	w.Line(1, "b.Grow(l)")
	w.Line(0, "")

	// Write URL base.
	w.Raw("\tb.WriteString(\"")
	w.Raw(routepattern.WithTrailingSlash(route))
	w.Raw("\")\n")
	w.Line(1, "if anyQuery {")
	w.Line(2, `b.WriteString("?")`)
	w.Line(1, "}")
	w.Line(0, "")

	// Reset n and write query params.
	w.Line(1, "n = 0")
	w.Line(0, "")

	for i, f := range fields {
		tag := structtag.QueryTagValue(f.Tag)
		w.writeIfZeroCheck(1, "query."+f.Name, f.Type)
		w.Line(2, "if n > 0 {")
		w.Line(3, `b.WriteString("&")`)
		w.Line(2, "}")
		// Only increment n if not the last field.
		if i < len(fields)-1 {
			w.Line(2, "n++")
		}
		w.Linef(2, "b.WriteString(%q)", tag+"=")
		w.Linef(2, "%s.WriteString(%s)", lo.builder, lo.queryStr[tag])
		w.Line(1, "}")
	}

	w.Line(0, "")
	w.Line(1, "return b.String()")
	w.Line(0, "}")
}

func (w *Writer) writeHrefFuncPathAndQuery(
	funcName, route string,
	params []pathParamInfo, fields []structFieldInfo,
) {
	// Function signature with path params + query struct.
	w.Raw("func ")
	w.Raw(funcName)
	w.Byte('(')
	w.writeTypedParams(params)
	w.Raw(", query Query")
	w.Raw(funcName)
	w.Raw(") string {\n")

	literals, _ := routepattern.Segments(route)
	if len(literals) != len(params)+1 {
		// Same guard as writeHrefFuncPathOnly: a rejected route must fail with
		// a diagnostic, not a stack trace.
		w.Line(1, `return ""`)
		w.Line(0, "}")
		return
	}
	lo := newHrefLocals(params, fields)

	// Pre-convert non-string path params.
	w.writePathPreConvert(params)

	// Pre-convert non-string query fields to strings.
	w.writeQueryPreConvert(lo, fields)

	// anyQuery check.
	w.writeAnyCheck(lo.anyQuery, fields)
	w.Line(0, "")

	// Length calculation.
	w.Linef(1, "var %s strings.Builder", lo.builder)

	// Path literal lengths.
	if len(literals) > 0 {
		w.Linef(1, "%s := len(%q) +", lo.length, literals[0])
		for i := 1; i < len(literals); i++ {
			if i-1 < len(params) {
				w.Linef(2, "len(%s) +", pathVarStrExpr(params[i-1]))
			}
			if i < len(literals)-1 || len(params) >= len(literals) {
				w.Linef(2, "len(%q) +", literals[i])
			} else {
				w.Linef(2, "len(%q)", literals[i])
			}
		}
		if len(params) >= len(literals) {
			w.Linef(2, "len(%s)", pathVarStrExpr(params[len(literals)-1]))
		}
	} else {
		w.Linef(1, "%s := 0", lo.length)
	}

	w.Linef(1, "if %s {", lo.anyQuery)
	w.Linef(2, "%s += len(\"?\")", lo.length)
	w.Line(1, "}")
	w.Line(0, "")

	w.Linef(1, "// %s = number of query params already accounted for (for '&')", lo.count)
	w.Linef(1, "%s := 0", lo.count)
	w.Line(0, "")

	for _, f := range fields {
		tag := structtag.QueryTagValue(f.Tag)
		w.writeIfZeroCheck(1, "query."+f.Name, f.Type)
		w.Linef(2, "if %s > 0 {", lo.count)
		w.Linef(3, "%s += len(\"&\")", lo.length)
		w.Line(2, "}")
		w.Linef(2, "%s++", lo.count)
		w.Linef(2, "%s += len(%q) + len(%s)", lo.length, tag+"=", lo.queryStr[tag])
		w.Line(1, "}")
	}
	w.Linef(1, "_ = %s", lo.count)
	w.Line(0, "")

	w.Linef(1, "%s.Grow(%s)", lo.builder, lo.length)
	w.Line(0, "")

	// Write path segments.
	for i, lit := range literals {
		w.Linef(1, "%s.WriteString(%q)", lo.builder, lit)
		if i < len(params) {
			w.Linef(1, "%s.WriteString(%s)", lo.builder, pathVarStrExpr(params[i]))
		}
	}

	w.Linef(1, "if %s {", lo.anyQuery)
	w.Linef(2, "%s.WriteString(\"?\")", lo.builder)
	w.Line(1, "}")
	w.Line(0, "")

	w.Linef(1, "%s = 0", lo.count)
	w.Line(0, "")

	for i, f := range fields {
		tag := structtag.QueryTagValue(f.Tag)
		w.writeIfZeroCheck(1, "query."+f.Name, f.Type)
		w.Linef(2, "if %s > 0 {", lo.count)
		w.Linef(3, "%s.WriteString(\"&\")", lo.builder)
		w.Line(2, "}")
		if i < len(fields)-1 {
			w.Linef(2, "%s++", lo.count)
		}
		w.Linef(2, "%s.WriteString(%q)", lo.builder, tag+"=")
		w.Linef(2, "%s.WriteString(%s)", lo.builder, lo.queryStr[tag])
		w.Line(1, "}")
	}

	w.Line(0, "")
	w.Linef(1, "return %s.String()", lo.builder)
	w.Line(0, "}")
}

func (w *Writer) writeHrefQueryType(funcName string, st *types.Struct) {
	w.Line(0, "")
	w.Linef(0, "// Query%s is the query parameters for %s", funcName, funcName)
	w.Linef(0, "type Query%s struct {", funcName)

	fields := w.structFields(st)

	// Find longest field name for alignment.
	maxNameLen := 0
	for _, f := range fields {
		if len(f.Name) > maxNameLen {
			maxNameLen = len(f.Name)
		}
	}
	// Find longest type name for alignment.
	maxTypeLen := 0
	for _, f := range fields {
		typeName := fieldTypeName(f.Type)
		if len(typeName) > maxTypeLen {
			maxTypeLen = len(typeName)
		}
	}

	for _, f := range fields {
		tag := structtag.QueryTagValue(f.Tag)
		typeName := fieldTypeName(f.Type)
		w.Linef(1, "\t%-*s %-*s `query:\"%s\"`",
			maxNameLen, f.Name, maxTypeLen, typeName, tag)
	}

	w.Line(0, "}")
}

// pathParamInfo describes a path variable with its route name and Go type.
type pathParamInfo struct {
	Name   string     // route variable name (e.g. "value")
	Type   types.Type // nil means string
	StrVar string     // variable name for string representation (e.g. "valueStr")
}

// pathParamInfos builds typed path parameter info from a path input and route variables.
// It computes conflict-free StrVar names for non-string parameters.
func (w *Writer) pathParamInfos(
	pathInput *model.Input, pathVars []string,
) []pathParamInfo {
	infos := make([]pathParamInfo, len(pathVars))
	if pathInput == nil {
		for i, v := range pathVars {
			infos[i] = pathParamInfo{Name: v, StrVar: v}
		}
		return infos
	}
	fields := w.structFields(pathInput.Type.Resolved)
	tagToType := make(map[string]types.Type, len(fields))
	for _, f := range fields {
		if tag := structtag.PathTagValue(f.Tag); tag != "" {
			tagToType[tag] = f.Type
		}
	}
	for i, v := range pathVars {
		infos[i] = pathParamInfo{Name: v, Type: tagToType[v]}
	}

	// Compute conflict-free StrVar for each parameter.
	// Non-string params need a string conversion variable named "s_<name>".
	// If that collides with another param name, prepend another "s_" prefix.
	names := make(map[string]bool, len(infos))
	for _, info := range infos {
		names[info.Name] = true
	}
	// Every parameter gets a local holding what goes into the URL:
	// the string form of a number, and the escaped form of a string. A value
	// carrying "/", "?", "&" or "#" would otherwise change what the URL addresses.
	for i := range infos {
		candidate := "s_" + infos[i].Name
		for names[candidate] {
			candidate = "s_" + candidate
		}
		infos[i].StrVar = candidate
		names[candidate] = true
	}
	return infos
}

// pathVarStrExpr returns the expression for a path variable's string representation.
func pathVarStrExpr(p pathParamInfo) string {
	return p.StrVar
}

// hrefLocals are the names the URL writer gives its own variables.
//
// A path variable is named by the route and may be called anything a Go identifier may
// be called, "b" included. A local the writer names without looking is a
// redeclaration in that function, and the generated package does not compile.
// Each name is therefore moved out of the way of whatever the route brought.
type hrefLocals struct {
	builder  string
	length   string
	count    string
	anyQuery string
	// beforeLen and afterLen hold the lengths of an action's
	// before and after expressions. Only the action writers declare them.
	beforeLen string
	afterLen  string
	// queryStr maps a query tag to the local holding its string form.
	// Only non-string fields need one.
	queryStr map[string]string
}

func newHrefLocals(params []pathParamInfo, fields []structFieldInfo) hrefLocals {
	taken := make(map[string]bool, len(params)*2+len(fields)+4)
	taken["query"] = true // the query struct parameter
	for _, p := range params {
		taken[p.Name] = true
		taken[p.StrVar] = true
	}
	pick := func(base string) string {
		name := base
		for taken[name] {
			name += "_"
		}
		taken[name] = true
		return name
	}
	lo := hrefLocals{
		builder:   pick("b"),
		length:    pick("l"),
		count:     pick("n"),
		anyQuery:  pick("anyQuery"),
		beforeLen: pick("bl"),
		afterLen:  pick("al"),
		queryStr:  make(map[string]string, len(fields)),
	}
	for _, f := range fields {
		tag := structtag.QueryTagValue(f.Tag)
		lo.queryStr[tag] = pick(tag + "Str")
	}
	return lo
}

// writeTypedParams writes a comma-separated typed parameter list.
func (w *Writer) writeTypedParams(params []pathParamInfo) {
	for i, p := range params {
		if i > 0 {
			w.Raw(", ")
		}
		w.Raw(p.Name)
		w.Byte(' ')
		w.Raw(fieldTypeName(p.Type))
	}
}

// writePathPreConvert emits the local that holds each path parameter's URL form:
// a number formatted, a string escaped.
//
// A path value belongs to one segment. Escaping is what keeps it there:
// PageItem("a/b") addresses /item/a%2Fb/, which the router hands back whole,
// rather than /item/a/b/, which it does not route at all.
func (w *Writer) writePathPreConvert(params []pathParamInfo) {
	for _, p := range params {
		w.Byte('\t')
		w.Raw(p.StrVar)
		w.Raw(" := ")
		switch {
		case gotypes.ImplementsTextMarshaler(p.Type):
			w.Rawf("url.PathEscape(textOf(%s))", p.Name)
		case p.Type == nil || !isFormattedType(p.Type):
			w.Rawf("url.PathEscape(%s)", p.Name)
		default:
			// A formatted number or bool carries nothing to escape.
			w.writeFormatExpr(p.Name, p.Type)
		}
		w.Byte('\n')
	}
}

// isFormattedType reports whether writeFormatExpr writes an expression for t.
// A type it does not format reaches a URL as the text the caller passes,
// which fieldTypeName declares as a string.
func isFormattedType(t types.Type) bool {
	return gotypes.IsInt(t) || gotypes.IsFloat(t) || gotypes.IsBool(t)
}

// writeFormatExpr emits a strconv.Format* expression for a non-string type.
func (w *Writer) writeFormatExpr(varName string, t types.Type) {
	if gotypes.IsInt(t) {
		_, unsigned := gotypes.IntParseInfo(t)
		typeName := gotypes.IntTypeName(t)
		if unsigned {
			if typeName != "uint64" {
				w.Rawf("strconv.FormatUint(uint64(%s), 10)", varName)
			} else {
				w.Rawf("strconv.FormatUint(%s, 10)", varName)
			}
		} else {
			if typeName != "int64" {
				w.Rawf("strconv.FormatInt(int64(%s), 10)", varName)
			} else {
				w.Rawf("strconv.FormatInt(%s, 10)", varName)
			}
		}
	} else if gotypes.IsFloat(t) {
		bits := gotypes.FloatBits(t)
		typeName := gotypes.FloatTypeName(t)
		if typeName != "float64" {
			w.Rawf("strconv.FormatFloat(float64(%s), 'f', -1, %d)", varName, bits)
		} else {
			w.Rawf("strconv.FormatFloat(%s, 'f', -1, %d)", varName, bits)
		}
	} else if gotypes.IsBool(t) {
		w.Rawf("strconv.FormatBool(%s)", varName)
	}
}

// writeZeroCheck writes the zero-value check expression for a field to the buffer.
func (w *Writer) writeZeroCheck(expr string, t types.Type) {
	w.Raw(expr)
	if gotypes.ImplementsTextMarshaler(t) {
		// The value travels as an interface, whose zero value is nil.
		w.Raw(" != nil")
		return
	}
	if gotypes.IsBool(t) {
		// bool: the expression itself is the condition
		return
	}
	if !isFormattedType(t) {
		w.Raw(` != ""`)
	} else {
		// int, float: != 0
		w.Raw(" != 0")
	}
}

// writeIfZeroCheck writes "if <expr> != <zero> {\n" at the given indent level.
func (w *Writer) writeIfZeroCheck(indent int, expr string, t types.Type) {
	for range indent {
		w.Byte('\t')
	}
	w.Raw("if ")
	w.writeZeroCheck(expr, t)
	w.Raw(" {\n")
}

// fieldTypeName returns the Go type name a builder takes the value as.
//
// A type of the app package cannot be named here: the app package imports the
// generated href and action packages, which makes the import back a cycle.
// A type that marshals itself is taken as the interface instead, which names no package.
// Everything else reaches a URL as the text the caller passes.
func fieldTypeName(t types.Type) string {
	if t == nil {
		return "string"
	}
	if gotypes.ImplementsTextMarshaler(t) {
		return "encoding.TextMarshaler"
	}
	if gotypes.IsString(t) {
		return "string"
	}
	if gotypes.IsInt(t) {
		return gotypes.IntTypeName(t)
	}
	if gotypes.IsFloat(t) {
		return gotypes.FloatTypeName(t)
	}
	if gotypes.IsBool(t) {
		return "bool"
	}
	return "string"
}

// writeQueryPreConvert emits the local that holds each query field's URL form:
// a number formatted, a string escaped.
//
// A query value that carries "&" or "#" would otherwise add
// parameters of its own, or cut the URL short.
func (w *Writer) writeQueryPreConvert(lo hrefLocals, fields []structFieldInfo) {
	if len(fields) == 0 {
		return
	}
	w.Line(1, "var (")
	for _, f := range fields {
		w.Linef(2, "%s string", lo.queryStr[structtag.QueryTagValue(f.Tag)])
	}
	w.Line(1, ")")
	w.Line(0, "")
	for _, f := range fields {
		tag := structtag.QueryTagValue(f.Tag)
		w.Raw("\tif ")
		w.writeZeroCheck("query."+f.Name, f.Type)
		w.Raw(" {\n")
		w.Rawf("\t\t%s = ", lo.queryStr[tag])
		switch {
		case gotypes.ImplementsTextMarshaler(f.Type):
			w.Rawf("url.QueryEscape(textOf(query.%s))", f.Name)
		case !isFormattedType(f.Type):
			w.Rawf("url.QueryEscape(query.%s)", f.Name)
		default:
			w.writeFormatExpr("query."+f.Name, f.Type)
		}
		w.Byte('\n')
		w.Line(1, "}")
	}
	w.Line(0, "")
}

// hasTextMarshalerFields reports whether any field marshals itself to text.
func hasTextMarshalerFields(fields []structFieldInfo) bool {
	for _, f := range fields {
		if gotypes.ImplementsTextMarshaler(f.Type) {
			return true
		}
	}
	return false
}

// hasNonStringFields reports whether any field has a non-string type.
func hasNonStringFields(fields []structFieldInfo) bool {
	for _, f := range fields {
		if !gotypes.IsString(f.Type) {
			return true
		}
	}
	return false
}
