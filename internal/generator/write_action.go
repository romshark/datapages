//go:embed action_static.go.txt
var actionStaticContent string

// WritePkgAction generates code for the datapagesgen/action package
// and appends it to buffer.
func (w *Writer) WritePkgAction(m *model.App) {
	// Count total page actions.
	nPageActions := 0
	for _, p := range m.Pages {
		nPageActions += len(p.Actions)
	}

	hasActions := len(m.Actions) > 0 || nPageActions > 0
	w.writeActionHeader(hasActions)

	type actionEntry struct {
		funcName   string
		httpMethod string
		route      string
		pathInput  *model.Input
		queryInput *model.Input
	}

	// Collect and sort app actions.
	appActions := make([]actionEntry, len(m.Actions))
	for i, a := range m.Actions {
		appActions[i] = actionEntry{
			funcName:   strings.ToUpper(a.HTTPMethod) + "App" + a.Name,
			httpMethod: a.HTTPMethod,
			route:      a.Route,
			pathInput:  a.InputPath,
			queryInput: a.InputQuery,
		}
	}
	slices.SortFunc(appActions, func(a, b actionEntry) int {
		return strings.Compare(a.funcName, b.funcName)
	})

	// Collect and sort page actions.
	pageActions := make([]actionEntry, 0, nPageActions)
	for _, p := range m.Pages {
		pageSuffix := stripPagePrefix(p.TypeName)
		for _, a := range p.Actions {
			pageActions = append(pageActions, actionEntry{
				funcName:   strings.ToUpper(a.HTTPMethod) + "Page" + pageSuffix + a.Name,
				httpMethod: a.HTTPMethod,
				route:      a.Route,
				pathInput:  a.InputPath,
				queryInput: a.InputQuery,
			})
		}
	}
	slices.SortFunc(pageActions, func(a, b actionEntry) int {
		return strings.Compare(a.funcName, b.funcName)
	})

	// Emit App actions first, then page actions.
	for _, a := range appActions {
		w.writeActionFunc(a.funcName, a.httpMethod, a.route, a.pathInput, a.queryInput)
	}
	for _, a := range pageActions {
		w.writeActionFunc(a.funcName, a.httpMethod, a.route, a.pathInput, a.queryInput)
	}
}

func (w *Writer) writeActionHeader(hasActions bool) {
	w.Line(0, "// Code generated by github.com/romshark/datapages; DO NOT EDIT.")
	w.Line(0, "")
	w.Line(0, "// Package action provides generators for datastar action attribute expressions.")
	w.Line(0, "// Use these in templates instead of hardcoding action URLs.")
	w.Line(0, "package action")
	if !hasActions {
		w.Line(0, "")
		w.Line(0, "// This package is empty because the application defines no actions.")
		w.Line(0, "// Define action handlers in your app package to generate action helpers.")
		return
	}
	w.Raw(actionStaticContent)
}

// writeActionRouteComment writes a doc comment line like
// "// FuncName references /route/\n".
// It strips {$} and ensures a trailing slash.
func (w *Writer) writeActionRouteComment(funcName, route string) {
	w.Raw("// ")
	w.Raw(funcName)
	w.Raw(" references ")
	w.Raw(routepattern.WithTrailingSlash(route))
	w.Byte('\n')
}

func (w *Writer) writeActionFunc(
	funcName string,
	httpMethod string,
	route string,
	pathInput *model.Input,
	queryInput *model.Input,
) {
	pathVars := slices.Collect(routepattern.Vars(route))
	hasPathVars := len(pathVars) > 0
	params := w.pathParamInfos(pathInput, pathVars)

	var queryFields []structFieldInfo
	if queryInput != nil {
		queryFields = w.structFields(queryInput.Type.Resolved)
	}
	hasQuery := len(queryFields) > 0

	method := strings.ToLower(httpMethod)

	// Doc comment.
	w.Line(0, "")
	w.writeActionRouteComment(funcName, route)

	if !hasPathVars && !hasQuery {
		w.Linef(0, "func %s(options ...option) string {", funcName)
		w.Line(1, "if len(options) == 0 {")
		w.Raw("\t\treturn \"@")
		w.Raw(method)
		w.Raw("('")
		w.Raw(routepattern.WithTrailingSlash(route))
		w.Raw("')\"\n")
		w.Line(1, "}")
		w.Line(1, "var b strings.Builder")
		w.Line(1, "bl, al := actionexpr.BeforeAfterLen(options)")
		w.Raw("\tb.Grow(bl + len(\"@")
		w.Raw(method)
		w.Raw("('")
		w.Raw(routepattern.WithTrailingSlash(route))
		w.Raw("'\") + actionexpr.OptionsLen(options) + len(\")\") + al")
		w.Raw(")\n")
		w.Line(1, "actionexpr.WriteBefore(&b, options)")
		w.Raw("\tb.WriteString(\"@")
		w.Raw(method)
		w.Raw("('")
		w.Raw(routepattern.WithTrailingSlash(route))
		w.Raw("'\")\n")
		w.Line(1, "actionexpr.WriteOptions(&b, options)")
		w.Line(1, "b.WriteByte(')')")
		w.Line(1, "actionexpr.WriteAfter(&b, options)")
		w.Line(1, "return b.String()")
		w.Line(0, "}")
		return
	}

	if hasPathVars && !hasQuery {
		w.writeActionFuncPathOnly(funcName, method, route, params)
		return
	}

	if !hasPathVars && hasQuery {
		w.writeActionFuncQueryOnly(funcName, method, route, queryFields)
		w.writeActionQueryType(funcName, queryFields)
		return
	}

	// Both path and query.
	w.writeActionFuncPathAndQuery(funcName, method, route, params, queryFields)
	w.writeActionQueryType(funcName, queryFields)
}

func (w *Writer) writeActionFuncPathOnly(
	funcName string,
	method string,
	route string,
	params []pathParamInfo,
) {
	lo := newHrefLocals(params, nil)
	literals, _ := routepattern.Segments(route)

	// func FuncName(params, options ...option) string {
	w.Raw("func ")
	w.Raw(funcName)
	w.Byte('(')
	w.writeTypedParams(params)
	w.Raw(", options ...option) string {\n")

	// Pre-convert non-string params to strings.
	w.writePathPreConvert(params)

	w.Linef(1, "var %s strings.Builder", lo.builder)
	w.Linef(1, "%s, %s := actionexpr.BeforeAfterLen(options)", lo.beforeLen, lo.afterLen)

	// b.Grow(bl + len("@method('lit0") +
	//  len(v0) + ... + len("litN'") + optionsLen + len(")") + al)
	w.Rawf("\t%s.Grow(%s + len(\"@", lo.builder, lo.beforeLen)
	w.Raw(method)
	w.Raw("('")
	w.Raw(literals[0])
	w.Raw("\")")
	for i, p := range params {
		w.Raw(" + len(")
		w.Raw(pathVarStrExpr(p))
		w.Raw(") + len(\"")
		w.Raw(literals[i+1])
		if i == len(params)-1 {
			w.Raw("'")
		}
		w.Raw("\")")
	}
	w.Raw(" + actionexpr.OptionsLen(options) + len(\")\") + al")
	w.Raw(")\n")

	// writeBefore + b.WriteString("@method('lit0")
	w.Linef(1, "actionexpr.WriteBefore(&%s, options)", lo.builder)
	w.Rawf("\t%s.WriteString(\"@", lo.builder)
	w.Raw(method)
	w.Raw("('")
	w.Raw(literals[0])
	w.Raw("\")\n")
	for i, p := range params {
		w.Raw("\tb.WriteString(")
		w.Raw(pathVarStrExpr(p))
		w.Raw(")\n")
		w.Rawf("\t%s.WriteString(\"", lo.builder)
		w.Raw(literals[i+1])
		if i == len(params)-1 {
			w.Raw("'")
		}
		w.Raw("\")\n")
	}

	w.Linef(1, "actionexpr.WriteOptions(&%s, options)", lo.builder)
	w.Line(1, "b.WriteByte(')')")
	w.Linef(1, "actionexpr.WriteAfter(&%s, options)", lo.builder)
	w.Linef(1, "return %s.String()", lo.builder)
	w.Line(0, "}")
}

func (w *Writer) writeActionFuncQueryOnly(
	funcName string,
	method string,
	route string,
	fields []structFieldInfo,
) {
	lo := newHrefLocals(nil, fields)
	// func FuncName(query QueryFuncName, options ...option) string {
	w.Raw("func ")
	w.Raw(funcName)
	w.Raw("(query Query")
	w.Raw(funcName)
	w.Raw(", options ...option) string {\n")

	// Pre-convert non-string fields to strings.
	w.writeQueryPreConvert(lo, fields)

	// anyQuery check.
	w.writeAnyCheck(lo.anyQuery, fields)
	w.Line(0, "")

	// Builder and length calculation.
	w.Linef(1, "var %s strings.Builder", lo.builder)
	w.Linef(1, "%s, %s := actionexpr.BeforeAfterLen(options)", lo.beforeLen, lo.afterLen)
	w.Raw("\tl := bl + len(\"@")
	w.Raw(method)
	w.Raw("('")
	w.Raw(routepattern.WithTrailingSlash(route))
	w.Raw("'\") + actionexpr.OptionsLen(options) + len(\")\") + al\n")
	w.Linef(1, "if %s {", lo.anyQuery)
	w.Linef(2, "%s += len(\"?\")", lo.length)
	w.Line(1, "}")

	// Query param length accumulation.
	w.Linef(1, "%s := 0", lo.count)
	for i, f := range fields {
		tag := structtag.QueryTagValue(f.Tag)
		w.writeIfZeroCheck(1, "query."+f.Name, f.Type)
		w.Linef(2, "if %s > 0 {", lo.count)
		w.Linef(3, "%s += len(\"&\")", lo.length)
		w.Line(2, "}")
		if i < len(fields)-1 {
			w.Linef(2, "%s++", lo.count)
		}
		w.Linef(2, "%s += len(%q) + len(%s)", lo.length, tag+"=", lo.queryStr[tag])
		w.Line(1, "}")
	}
	w.Line(0, "")

	// Grow and write.
	w.Linef(1, "%s.Grow(%s)", lo.builder, lo.length)
	w.Line(0, "")
	w.Linef(1, "actionexpr.WriteBefore(&%s, options)", lo.builder)
	w.Rawf("\t%s.WriteString(\"@", lo.builder)
	w.Raw(method)
	w.Raw("('")
	w.Raw(routepattern.WithTrailingSlash(route))
	w.Raw("\")\n")
	w.Linef(1, "if %s {", lo.anyQuery)
	w.Linef(2, "%s.WriteString(\"?\")", lo.builder)
	w.Line(1, "}")

	// Write query params.
	w.Linef(1, "%s = 0", lo.count)
	for i, f := range fields {
		tag := structtag.QueryTagValue(f.Tag)
		w.writeIfZeroCheck(1, "query."+f.Name, f.Type)
		w.Linef(2, "if %s > 0 {", lo.count)
		w.Linef(3, "%s.WriteString(\"&\")", lo.builder)
		w.Line(2, "}")
		if i < len(fields)-1 {
			w.Linef(2, "%s++", lo.count)
		}
		w.Linef(2, "%s.WriteString(%q)", lo.builder, tag+"=")
		w.Linef(2, "%s.WriteString(%s)", lo.builder, lo.queryStr[tag])
		w.Line(1, "}")
	}

	w.Line(1, `b.WriteString("'")`)
	w.Linef(1, "actionexpr.WriteOptions(&%s, options)", lo.builder)
	w.Line(1, "b.WriteByte(')')")
	w.Linef(1, "actionexpr.WriteAfter(&%s, options)", lo.builder)
	w.Line(0, "")
	w.Linef(1, "return %s.String()", lo.builder)
	w.Line(0, "}")
}

func (w *Writer) writeActionFuncPathAndQuery(
	funcName string,
	method string,
	route string,
	params []pathParamInfo,
	fields []structFieldInfo,
) {
	lo := newHrefLocals(params, fields)
	literals, _ := routepattern.Segments(route)

	// func FuncName(params, query QueryFuncName, options ...option) string {
	w.Raw("func ")
	w.Raw(funcName)
	w.Byte('(')
	w.writeTypedParams(params)
	w.Raw(", query Query")
	w.Raw(funcName)
	w.Raw(", options ...option) string {\n")

	// Pre-convert non-string path params.
	w.writePathPreConvert(params)

	// Pre-convert non-string query fields to strings.
	w.writeQueryPreConvert(lo, fields)

	// anyQuery check.
	w.writeAnyCheck(lo.anyQuery, fields)
	w.Line(0, "")

	// Builder and length calculation.
	w.Linef(1, "var %s strings.Builder", lo.builder)
	w.Linef(1, "%s, %s := actionexpr.BeforeAfterLen(options)", lo.beforeLen, lo.afterLen)

	// l := bl + len("@method('lit0") + len(v0) + len("lit1") + ... + len("')")
	w.Raw("\tl := bl + len(\"@")
	w.Raw(method)
	w.Raw("('")
	w.Raw(literals[0])
	w.Raw("\")")
	for i, p := range params {
		w.Raw(" + len(")
		w.Raw(pathVarStrExpr(p))
		w.Raw(") + len(\"")
		w.Raw(literals[i+1])
		w.Raw("\")")
	}
	w.Raw(" + len(\"'\") + actionexpr.OptionsLen(options) + len(\")\") + al\n")

	w.Linef(1, "if %s {", lo.anyQuery)
	w.Linef(2, "%s += len(\"?\")", lo.length)
	w.Line(1, "}")

	// Query param length accumulation.
	w.Linef(1, "%s := 0", lo.count)
	for i, f := range fields {
		tag := structtag.QueryTagValue(f.Tag)
		w.writeIfZeroCheck(1, "query."+f.Name, f.Type)
		w.Linef(2, "if %s > 0 {", lo.count)
		w.Linef(3, "%s += len(\"&\")", lo.length)
		w.Line(2, "}")
		if i < len(fields)-1 {
			w.Linef(2, "%s++", lo.count)
		}
		w.Linef(2, "%s += len(%q) + len(%s)", lo.length, tag+"=", lo.queryStr[tag])
		w.Line(1, "}")
	}
	w.Line(0, "")

	// Grow and write path segments.
	w.Linef(1, "%s.Grow(%s)", lo.builder, lo.length)
	w.Line(0, "")
	w.Linef(1, "actionexpr.WriteBefore(&%s, options)", lo.builder)
	w.Rawf("\t%s.WriteString(\"@", lo.builder)
	w.Raw(method)
	w.Raw("('")
	w.Raw(literals[0])
	w.Raw("\")\n")
	for i, p := range params {
		w.Raw("\tb.WriteString(")
		w.Raw(pathVarStrExpr(p))
		w.Raw(")\n")
		w.Rawf("\t%s.WriteString(\"", lo.builder)
		w.Raw(literals[i+1])
		w.Raw("\")\n")
	}

	w.Linef(1, "if %s {", lo.anyQuery)
	w.Linef(2, "%s.WriteString(\"?\")", lo.builder)
	w.Line(1, "}")

	// Write query params.
	w.Linef(1, "%s = 0", lo.count)
	for i, f := range fields {
		tag := structtag.QueryTagValue(f.Tag)
		w.writeIfZeroCheck(1, "query."+f.Name, f.Type)
		w.Linef(2, "if %s > 0 {", lo.count)
		w.Linef(3, "%s.WriteString(\"&\")", lo.builder)
		w.Line(2, "}")
		if i < len(fields)-1 {
			w.Linef(2, "%s++", lo.count)
		}
		w.Linef(2, "%s.WriteString(%q)", lo.builder, tag+"=")
		w.Linef(2, "%s.WriteString(%s)", lo.builder, lo.queryStr[tag])
		w.Line(1, "}")
	}

	w.Line(1, `b.WriteString("'")`)
	w.Linef(1, "actionexpr.WriteOptions(&%s, options)", lo.builder)
	w.Line(1, "b.WriteByte(')')")
	w.Linef(1, "actionexpr.WriteAfter(&%s, options)", lo.builder)
	w.Line(0, "")
	w.Linef(1, "return %s.String()", lo.builder)
	w.Line(0, "}")
}

func (w *Writer) writeActionQueryType(funcName string, fields []structFieldInfo) {
	w.Line(0, "")
	w.Raw("type Query")
	w.Raw(funcName)
	w.Raw(" struct {\n")

	// Find longest field name for alignment.
	maxNameLen := 0
	for _, f := range fields {
		if len(f.Name) > maxNameLen {
			maxNameLen = len(f.Name)
		}
	}
	// Find longest type name for alignment.
	maxTypeLen := 0
	for _, f := range fields {
		typeName := fieldTypeName(f.Type)
		if len(typeName) > maxTypeLen {
			maxTypeLen = len(typeName)
		}
	}

	for _, f := range fields {
		tag := structtag.QueryTagValue(f.Tag)
		typeName := fieldTypeName(f.Type)
		w.Linef(1, "\t%-*s %-*s `query:\"%s\"`",
			maxNameLen, f.Name, maxTypeLen, typeName, tag)
	}

	w.Line(0, "}")
}
