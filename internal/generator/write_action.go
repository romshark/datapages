//go:embed action_static.go.txt
var actionStaticContent string

// WritePkgAction generates code for the datapagesgen/action package
// and appends it to buffer.
func (w *Writer) WritePkgAction(m *model.App) {
	// Count total page actions.
	nPageActions := 0
	for _, p := range m.Pages {
		nPageActions += len(p.Actions)
	}

	hasActions := len(m.Actions) > 0 || nPageActions > 0
	w.writeActionHeader(hasActions)
	if hasActions && w.actionsNeedText(m) {
		w.writeTextOf()
	}

	// An action reaches a template as action.PageFoo.Bar.POST: three
	// identifiers, each a field or method of the namespace above it.
	// Two model names never concatenate, which PageUser.POSTSettingsSave and
	// PageUserSettings.POSTSave would spell as one.
	//
	// The unexported types below do concatenate, separated by "_", which no
	// model name may contain: no pair of models spells one of them two ways.
	type verbEntry struct {
		httpMethod string
		route      string
		pathInput  *model.Input
		queryInput *model.Input
	}
	type actionEntry struct {
		name  string // the action name without its HTTP method, e.g. "SettingsSave"
		verbs []verbEntry
	}
	byOwner := map[string]map[string][]verbEntry{}
	add := func(owner string, a *model.Handler) {
		if byOwner[owner] == nil {
			byOwner[owner] = map[string][]verbEntry{}
		}
		byOwner[owner][a.Name] = append(byOwner[owner][a.Name], verbEntry{
			httpMethod: a.HTTPMethod,
			route:      a.Route,
			pathInput:  a.InputPath,
			queryInput: a.InputQuery,
		})
	}
	for _, a := range m.Actions {
		add("App", a)
	}
	for _, p := range m.Pages {
		for _, a := range p.Actions {
			add(p.TypeName, a)
		}
	}

	// App first, then the pages by name: the order a reader scans.
	owners := make([]string, 0, len(byOwner))
	for owner := range byOwner {
		if owner != "App" {
			owners = append(owners, owner)
		}
	}
	slices.Sort(owners)
	if _, ok := byOwner["App"]; ok {
		owners = append([]string{"App"}, owners...)
	}

	for _, owner := range owners {
		actions := make([]actionEntry, 0, len(byOwner[owner]))
		for name, verbs := range byOwner[owner] {
			slices.SortFunc(verbs, func(a, b verbEntry) int {
				return strings.Compare(a.httpMethod, b.httpMethod)
			})
			actions = append(actions, actionEntry{name: name, verbs: verbs})
		}
		slices.SortFunc(actions, func(a, b actionEntry) int {
			return strings.Compare(a.name, b.name)
		})

		ownerRecv := actionRecvType(owner)
		w.Line(0, "")
		w.Linef(0, "var %s %s", owner, ownerRecv)
		w.Line(0, "")
		w.Linef(0, "type %s struct {", ownerRecv)
		for _, a := range actions {
			w.Linef(1, "%s %s", a.name, actionRecvType(owner)+"_"+a.name)
		}
		w.Line(0, "}")

		for _, a := range actions {
			recv := ownerRecv + "_" + a.name
			w.Line(0, "")
			w.Linef(0, "type %s struct{}", recv)
			for _, v := range a.verbs {
				w.writeActionFunc(recv, strings.ToUpper(v.httpMethod),
					v.httpMethod, v.route, v.pathInput, v.queryInput)
			}
		}
	}
}

// actionRecvType is the unexported receiver type of an owner's namespace:
// "PageFoo" -> "pageFoo", "App" -> "app".
func actionRecvType(owner string) string {
	return strings.ToLower(owner[:1]) + owner[1:]
}

// actionQueryType is the unexported type of an action's query argument.
// A template never names it: [Writer.writeActionQueryCtor] builds it.
func actionQueryType(recv, verb string) string {
	return recv + "_" + verb + "Query"
}

func (w *Writer) writeActionHeader(hasActions bool) {
	w.Line(0, "// Code generated by github.com/romshark/datapages; DO NOT EDIT.")
	w.Line(0, "")
	w.Line(0, "// Package action provides generators for datastar action attribute expressions.")
	w.Line(0, "// Use these in templates instead of hardcoding action URLs.")
	w.Line(0, "package action")
	if !hasActions {
		w.Line(0, "")
		w.Line(0, "// This package is empty because the application defines no actions.")
		w.Line(0, "// Define action handlers in your app package to generate action helpers.")
		return
	}
	w.Raw(actionStaticContent)
}

// actionsNeedText reports whether any action takes a value that marshals
// itself to text, which is what [Writer.writeTextOf] renders.
func (w *Writer) actionsNeedText(m *model.App) bool {
	marshals := func(in *model.Input) bool {
		if in == nil {
			return false
		}
		return hasTextMarshalerFields(w.structFields(in.Type.Resolved))
	}
	for _, a := range m.Actions {
		if marshals(a.InputPath) || marshals(a.InputQuery) {
			return true
		}
	}
	for _, p := range m.Pages {
		for _, a := range p.Actions {
			if marshals(a.InputPath) || marshals(a.InputQuery) {
				return true
			}
		}
	}
	return false
}

// writeActionRouteComment writes a doc comment line like
// "// Method references /route/\n".
// It strips {$} and ensures a trailing slash.
func (w *Writer) writeActionRouteComment(name, route string) {
	w.Raw("// ")
	w.Raw(name)
	w.Raw(" references ")
	w.Raw(routepattern.WithTrailingSlash(route))
	w.Byte('\n')
}

// writeActionMethodHead writes "func (recv) Name" of an action method.
func (w *Writer) writeActionMethodHead(recv, name string) {
	w.Rawf("func (%s) %s", recv, name)
}

func (w *Writer) writeActionFunc(
	recv, methodName string,
	httpMethod string,
	route string,
	pathInput *model.Input,
	queryInput *model.Input,
) {
	queryType := actionQueryType(recv, methodName)
	pathVars := slices.Collect(routepattern.Vars(route))
	hasPathVars := len(pathVars) > 0
	params := w.pathParamInfos(pathInput, pathVars)

	var queryFields []structFieldInfo
	if queryInput != nil {
		queryFields = w.structFields(queryInput.Type.Resolved)
	}
	hasQuery := len(queryFields) > 0

	method := strings.ToLower(httpMethod)

	// Doc comment.
	w.Line(0, "")
	w.writeActionRouteComment(methodName, route)

	if !hasPathVars && !hasQuery {
		w.writeActionMethodHead(recv, methodName)
		w.writeParamList([]string{"options ...option"})
		w.Raw(" string {\n")
		w.Line(1, "if len(options) == 0 {")
		w.Raw("\t\treturn \"@")
		w.Raw(method)
		w.Raw("('")
		w.Raw(routepattern.WithTrailingSlash(route))
		w.Raw("')\"\n")
		w.Line(1, "}")
		w.Line(1, "var b strings.Builder")
		w.Line(1, "bl, al := actionexpr.BeforeAfterLen(options)")
		w.Raw("\tb.Grow(bl + len(\"@")
		w.Raw(method)
		w.Raw("('")
		w.Raw(routepattern.WithTrailingSlash(route))
		w.Raw("'\") + actionexpr.OptionsLen(options) + len(\")\") + al")
		w.Raw(")\n")
		w.Line(1, "actionexpr.WriteBefore(&b, options)")
		w.Raw("\tb.WriteString(\"@")
		w.Raw(method)
		w.Raw("('")
		w.Raw(routepattern.WithTrailingSlash(route))
		w.Raw("'\")\n")
		w.Line(1, "actionexpr.WriteOptions(&b, options)")
		w.Line(1, "b.WriteByte(')')")
		w.Line(1, "actionexpr.WriteAfter(&b, options)")
		w.Line(1, "return b.String()")
		w.Line(0, "}")
		return
	}

	if hasPathVars && !hasQuery {
		w.writeActionFuncPathOnly(recv, methodName, method, route, params)
		return
	}

	if !hasPathVars && hasQuery {
		w.writeActionFuncQueryOnly(recv, methodName, queryType,
			method, route, queryFields)
		w.writeActionQueryType(queryType, queryFields)
		w.writeActionQueryCtor(recv, methodName, queryType, queryFields)
		return
	}

	// Both path and query.
	w.writeActionFuncPathAndQuery(recv, methodName, queryType,
		method, route, params, queryFields)
	w.writeActionQueryType(queryType, queryFields)
	w.writeActionQueryCtor(recv, methodName, queryType, queryFields)
}

func (w *Writer) writeActionFuncPathOnly(
	recv, methodName string,
	method string,
	route string,
	params []pathParamInfo,
) {
	lo := newHrefLocals(params, nil)
	literals, _ := routepattern.Segments(route)

	// func (recv) Method(params, options ...option) string {
	w.writeActionMethodHead(recv, methodName)
	w.writeParamList(append(typedParams(params), lo.options+" ...option"))
	w.Raw(" string {\n")

	// Pre-convert non-string params to strings.
	w.writePathPreConvert(params)

	w.Linef(1, "var %s strings.Builder", lo.builder)
	w.Linef(1, "%s, %s := actionexpr.BeforeAfterLen(%s)",
		lo.beforeLen, lo.afterLen, lo.options)

	// b.Grow(bl + len("@method('lit0") +
	//  len(v0) + ... + len("litN'") + optionsLen + len(")") + al)
	w.Rawf("\t%s.Grow(%s + len(\"@", lo.builder, lo.beforeLen)
	w.Raw(method)
	w.Raw("('")
	w.Raw(literals[0])
	w.Raw("\")")
	for i, p := range params {
		w.Raw(" + len(")
		w.Raw(pathVarStrExpr(p))
		w.Raw(") + len(\"")
		w.Raw(literals[i+1])
		if i == len(params)-1 {
			w.Raw("'")
		}
		w.Raw("\")")
	}
	w.Rawf(" + actionexpr.OptionsLen(%s) + len(\")\") + %s", lo.options, lo.afterLen)
	w.Raw(")\n")

	// writeBefore + b.WriteString("@method('lit0")
	w.Linef(1, "actionexpr.WriteBefore(&%s, %s)", lo.builder, lo.options)
	w.Rawf("\t%s.WriteString(\"@", lo.builder)
	w.Raw(method)
	w.Raw("('")
	w.Raw(literals[0])
	w.Raw("\")\n")
	for i, p := range params {
		w.Rawf("\t%s.WriteString(", lo.builder)
		w.Raw(pathVarStrExpr(p))
		w.Raw(")\n")
		w.Rawf("\t%s.WriteString(\"", lo.builder)
		w.Raw(literals[i+1])
		if i == len(params)-1 {
			w.Raw("'")
		}
		w.Raw("\")\n")
	}

	w.Linef(1, "actionexpr.WriteOptions(&%s, %s)", lo.builder, lo.options)
	w.Linef(1, "%s.WriteByte(')')", lo.builder)
	w.Linef(1, "actionexpr.WriteAfter(&%s, %s)", lo.builder, lo.options)
	w.Linef(1, "return %s.String()", lo.builder)
	w.Line(0, "}")
}

func (w *Writer) writeActionFuncQueryOnly(
	recv, methodName, queryType string,
	method string,
	route string,
	fields []structFieldInfo,
) {
	lo := newHrefLocals(nil, fields)
	// func (recv) Method(query QueryType, options ...option) string {
	w.writeActionMethodHead(recv, methodName)
	w.writeParamList([]string{
		lo.query + " " + queryType,
		lo.options + " ...option",
	})
	w.Raw(" string {\n")

	// Pre-convert non-string fields to strings.
	w.writeQueryPreConvert(lo, fields)

	// anyQuery check.
	w.writeAnyCheck(lo.anyQuery, lo.query, fields)
	w.Line(0, "")

	// Builder and length calculation.
	w.Linef(1, "var %s strings.Builder", lo.builder)
	w.Linef(1, "%s, %s := actionexpr.BeforeAfterLen(%s)",
		lo.beforeLen, lo.afterLen, lo.options)
	w.Rawf("\t%s := %s + len(\"@", lo.length, lo.beforeLen)
	w.Raw(method)
	w.Raw("('")
	w.Raw(routepattern.WithTrailingSlash(route))
	w.Rawf("'\") + actionexpr.OptionsLen(%s) + len(\")\") + %s\n",
		lo.options, lo.afterLen)
	w.Linef(1, "if %s {", lo.anyQuery)
	w.Linef(2, "%s += len(\"?\")", lo.length)
	w.Line(1, "}")

	// Query param length accumulation.
	w.Linef(1, "%s := 0", lo.count)
	for i, f := range fields {
		tag := structtag.QueryTagValue(f.Tag)
		w.writeIfZeroCheck(1, lo.query+"."+f.Name, f.Type)
		w.Linef(2, "if %s > 0 {", lo.count)
		w.Linef(3, "%s += len(\"&\")", lo.length)
		w.Line(2, "}")
		if i < len(fields)-1 {
			w.Linef(2, "%s++", lo.count)
		}
		w.Linef(2, "%s += len(%q) + len(%s)", lo.length, tag+"=", lo.queryStr[tag])
		w.Line(1, "}")
	}
	w.Line(0, "")

	// Grow and write.
	w.Linef(1, "%s.Grow(%s)", lo.builder, lo.length)
	w.Line(0, "")
	w.Linef(1, "actionexpr.WriteBefore(&%s, %s)", lo.builder, lo.options)
	w.Rawf("\t%s.WriteString(\"@", lo.builder)
	w.Raw(method)
	w.Raw("('")
	w.Raw(routepattern.WithTrailingSlash(route))
	w.Raw("\")\n")
	w.Linef(1, "if %s {", lo.anyQuery)
	w.Linef(2, "%s.WriteString(\"?\")", lo.builder)
	w.Line(1, "}")

	// Write query params.
	w.Linef(1, "%s = 0", lo.count)
	for i, f := range fields {
		tag := structtag.QueryTagValue(f.Tag)
		w.writeIfZeroCheck(1, lo.query+"."+f.Name, f.Type)
		w.Linef(2, "if %s > 0 {", lo.count)
		w.Linef(3, "%s.WriteString(\"&\")", lo.builder)
		w.Line(2, "}")
		if i < len(fields)-1 {
			w.Linef(2, "%s++", lo.count)
		}
		w.Linef(2, "%s.WriteString(%q)", lo.builder, tag+"=")
		w.Linef(2, "%s.WriteString(%s)", lo.builder, lo.queryStr[tag])
		w.Line(1, "}")
	}

	w.Linef(1, `%s.WriteString("'")`, lo.builder)
	w.Linef(1, "actionexpr.WriteOptions(&%s, %s)", lo.builder, lo.options)
	w.Linef(1, "%s.WriteByte(')')", lo.builder)
	w.Linef(1, "actionexpr.WriteAfter(&%s, %s)", lo.builder, lo.options)
	w.Line(0, "")
	w.Linef(1, "return %s.String()", lo.builder)
	w.Line(0, "}")
}

func (w *Writer) writeActionFuncPathAndQuery(
	recv, methodName, queryType string,
	method string,
	route string,
	params []pathParamInfo,
	fields []structFieldInfo,
) {
	lo := newHrefLocals(params, fields)
	literals, _ := routepattern.Segments(route)

	// func (recv) Method(params, query QueryType, options ...option) string {
	w.writeActionMethodHead(recv, methodName)
	w.writeParamList(append(typedParams(params),
		lo.query+" "+queryType,
		lo.options+" ...option"))
	w.Raw(" string {\n")

	// Pre-convert non-string path params.
	w.writePathPreConvert(params)

	// Pre-convert non-string query fields to strings.
	w.writeQueryPreConvert(lo, fields)

	// anyQuery check.
	w.writeAnyCheck(lo.anyQuery, lo.query, fields)
	w.Line(0, "")

	// Builder and length calculation.
	w.Linef(1, "var %s strings.Builder", lo.builder)
	w.Linef(1, "%s, %s := actionexpr.BeforeAfterLen(%s)",
		lo.beforeLen, lo.afterLen, lo.options)

	// l := bl + len("@method('lit0") + len(v0) + len("lit1") + ... + len("')")
	w.Rawf("\t%s := %s + len(\"@", lo.length, lo.beforeLen)
	w.Raw(method)
	w.Raw("('")
	w.Raw(literals[0])
	w.Raw("\")")
	for i, p := range params {
		w.Raw(" + len(")
		w.Raw(pathVarStrExpr(p))
		w.Raw(") + len(\"")
		w.Raw(literals[i+1])
		w.Raw("\")")
	}
	w.Rawf(" + len(\"'\") + actionexpr.OptionsLen(%s) + len(\")\") + %s\n",
		lo.options, lo.afterLen)

	w.Linef(1, "if %s {", lo.anyQuery)
	w.Linef(2, "%s += len(\"?\")", lo.length)
	w.Line(1, "}")

	// Query param length accumulation.
	w.Linef(1, "%s := 0", lo.count)
	for i, f := range fields {
		tag := structtag.QueryTagValue(f.Tag)
		w.writeIfZeroCheck(1, lo.query+"."+f.Name, f.Type)
		w.Linef(2, "if %s > 0 {", lo.count)
		w.Linef(3, "%s += len(\"&\")", lo.length)
		w.Line(2, "}")
		if i < len(fields)-1 {
			w.Linef(2, "%s++", lo.count)
		}
		w.Linef(2, "%s += len(%q) + len(%s)", lo.length, tag+"=", lo.queryStr[tag])
		w.Line(1, "}")
	}
	w.Line(0, "")

	// Grow and write path segments.
	w.Linef(1, "%s.Grow(%s)", lo.builder, lo.length)
	w.Line(0, "")
	w.Linef(1, "actionexpr.WriteBefore(&%s, %s)", lo.builder, lo.options)
	w.Rawf("\t%s.WriteString(\"@", lo.builder)
	w.Raw(method)
	w.Raw("('")
	w.Raw(literals[0])
	w.Raw("\")\n")
	for i, p := range params {
		w.Rawf("\t%s.WriteString(", lo.builder)
		w.Raw(pathVarStrExpr(p))
		w.Raw(")\n")
		w.Rawf("\t%s.WriteString(\"", lo.builder)
		w.Raw(literals[i+1])
		w.Raw("\")\n")
	}

	w.Linef(1, "if %s {", lo.anyQuery)
	w.Linef(2, "%s.WriteString(\"?\")", lo.builder)
	w.Line(1, "}")

	// Write query params.
	w.Linef(1, "%s = 0", lo.count)
	for i, f := range fields {
		tag := structtag.QueryTagValue(f.Tag)
		w.writeIfZeroCheck(1, lo.query+"."+f.Name, f.Type)
		w.Linef(2, "if %s > 0 {", lo.count)
		w.Linef(3, "%s.WriteString(\"&\")", lo.builder)
		w.Line(2, "}")
		if i < len(fields)-1 {
			w.Linef(2, "%s++", lo.count)
		}
		w.Linef(2, "%s.WriteString(%q)", lo.builder, tag+"=")
		w.Linef(2, "%s.WriteString(%s)", lo.builder, lo.queryStr[tag])
		w.Line(1, "}")
	}

	w.Linef(1, `%s.WriteString("'")`, lo.builder)
	w.Linef(1, "actionexpr.WriteOptions(&%s, %s)", lo.builder, lo.options)
	w.Linef(1, "%s.WriteByte(')')", lo.builder)
	w.Linef(1, "actionexpr.WriteAfter(&%s, %s)", lo.builder, lo.options)
	w.Line(0, "")
	w.Linef(1, "return %s.String()", lo.builder)
	w.Line(0, "}")
}

// writeActionQueryCtor writes the method that builds an action's query argument.
// Its type is unexported, which leaves this the only way a template
// has of producing one: the type never appears in a name a template writes.
func (w *Writer) writeActionQueryCtor(
	recv, methodName, queryType string, fields []structFieldInfo,
) {
	w.Line(0, "")
	w.Rawf("func (%s) %sQuery", recv, methodName)
	ctorParams := make([]string, len(fields))
	for i, f := range fields {
		ctorParams[i] = queryCtorParam(f.Name) + " " + fieldTypeName(f.Type)
	}
	w.writeParamList(ctorParams)
	w.Rawf(" %s {\n", queryType)
	w.Linef(1, "return %s{", queryType)
	for _, f := range fields {
		w.Linef(2, "%s: %s,", f.Name, queryCtorParam(f.Name))
	}
	w.Line(1, "}")
	w.Line(0, "}")
}

// queryCtorParam names the constructor parameter of a query field.
// The field is exported, the parameter is not: a field named "Options" would
// otherwise take the name the variadic holds.
func queryCtorParam(fieldName string) string {
	return "v" + fieldName
}

func (w *Writer) writeActionQueryType(queryType string, fields []structFieldInfo) {
	w.Line(0, "")
	w.Raw("type ")
	w.Raw(queryType)
	w.Raw(" struct {\n")

	// Find longest field name for alignment.
	maxNameLen := 0
	for _, f := range fields {
		if len(f.Name) > maxNameLen {
			maxNameLen = len(f.Name)
		}
	}
	// Find longest type name for alignment.
	maxTypeLen := 0
	for _, f := range fields {
		typeName := fieldTypeName(f.Type)
		if len(typeName) > maxTypeLen {
			maxTypeLen = len(typeName)
		}
	}

	for _, f := range fields {
		tag := structtag.QueryTagValue(f.Tag)
		typeName := fieldTypeName(f.Type)
		w.Linef(1, "\t%-*s %-*s `query:\"%s\"`",
			maxNameLen, f.Name, maxTypeLen, typeName, tag)
	}

	w.Line(0, "}")
}
