func (w *Writer) writeSetupHandlers(m *model.App) {
	w.Line(0, "")
	w.Line(0, "func setupHandlers(s *Server) {")
	w.Line(1, "// Pages")

	for _, p := range m.Pages {
		if p.GET == nil || p.GET.OutputBody == nil {
			continue
		}

		routeForHandler := routepattern.WithTrailingSlash(p.Route)

		if p.PageSpecialization == model.PageTypeIndex {
			// Index page: GET /
			w.Line(1, "s.Mux().HandleFunc(")
			w.Line(2, "\"GET /\",")
			w.Raw("\t\ts.handle")
			w.Raw(p.TypeName)
			w.Raw("GET)\n")
		} else if routepattern.EndsInWildcard(p.Route) {
			// A {name...} wildcard runs to the end of the path already.
			// Marking the end after it puts the wildcard in the middle,
			// which is a pattern net/http will not parse.
			w.Line(1, "s.Mux().HandleFunc(")
			w.Raw("\t\t\"GET ")
			w.Raw(p.Route)
			w.Raw("\",\n")
			w.Raw("\t\ts.handle")
			w.Raw(p.TypeName)
			w.Raw("GET)\n")
		} else {
			w.Line(1, "s.Mux().HandleFunc(")
			w.Raw("\t\t\"GET ")
			w.Raw(routeForHandler)
			w.Raw("{$}\",\n")
			w.Raw("\t\ts.handle")
			w.Raw(p.TypeName)
			w.Raw("GET)\n")
		}

		// Stream endpoint.
		if pageHasStream(p) {
			streamPath := routeStreamPath(p.Route)

			w.Line(1, "s.Mux().HandleFunc(")
			w.Raw("\t\t\"GET ")
			w.Raw(streamPath)
			w.Raw("{$}\",\n")
			w.Raw("\t\ts.handle")
			w.Raw(p.TypeName)
			w.Raw("GETStream)\n")

			if pageHasAnonStream(p, w.eventMap) {
				w.Line(1, "s.Mux().HandleFunc(")
				w.Raw("\t\t\"GET ")
				w.Raw(streamPath)
				w.Raw("anon/{$}\",\n")
				w.Raw("\t\ts.handle")
				w.Raw(p.TypeName)
				w.Raw("GETStreamAnon)\n")
			}
		}
	}

	// App-level actions.
	for _, h := range m.Actions {
		route := routepattern.WithTrailingSlash(h.Route)
		method := strings.ToUpper(h.HTTPMethod)

		w.Line(1, "s.Mux().HandleFunc(")
		w.Raw("\t\t\"")
		w.Raw(method)
		w.Byte(' ')
		w.Raw(route)
		w.Raw("{$}\",\n")
		w.Raw("\t\ts.handle")
		w.Raw(method)
		w.Raw(h.Name)
		w.Raw(")\n")
	}

	// Page actions.
	for _, p := range m.Pages {
		for _, h := range p.Actions {
			route := routepattern.WithTrailingSlash(h.Route)
			method := strings.ToUpper(h.HTTPMethod)

			w.Line(1, "s.Mux().HandleFunc(")
			w.Raw("\t\t\"")
			w.Raw(method)
			w.Byte(' ')
			w.Raw(route)
			w.Raw("{$}\",\n")
			w.Raw("\t\ts.handle")
			w.Raw(p.TypeName)
			w.Raw(method)
			w.Raw(h.Name)
			w.Raw(")\n")
		}
	}

	w.Line(0, "}")
}

func (w *Writer) writeHTTPErrFallback() {
	if !w.usage.errSentinels {
		w.Raw(`	const code = http.StatusInternalServerError
	http.Error(w, http.StatusText(code), code)
`)
		return
	}
	w.Raw(`	switch {
	case errors.Is(err, datapages.ErrBadRequest):
		http.Error(w, http.StatusText(http.StatusBadRequest), http.StatusBadRequest)
	case errors.Is(err, datapages.ErrForbidden):
		http.Error(w, http.StatusText(http.StatusForbidden), http.StatusForbidden)
	case errors.Is(err, datapages.ErrNotFound):
		http.Error(w, http.StatusText(http.StatusNotFound), http.StatusNotFound)
	case errors.Is(err, datapages.ErrConflict):
		http.Error(w, http.StatusText(http.StatusConflict), http.StatusConflict)
	default:
		http.Error(w, http.StatusText(http.StatusInternalServerError), http.StatusInternalServerError)
	}
`)
}

// needsCSRFOnly reports whether a handler has to run the session check for the
// CSRF token alone, because it reads nothing of the session itself.
//
// The check lives inside the session helper. A state-changing action that
// declares neither session nor sessionToken would never call it,
// and a cross-site page can make a browser send exactly that request.
func needsCSRFOnly(h *model.Handler, m *model.App) bool {
	if m.Session == nil {
		return false
	}
	switch strings.ToUpper(h.HTTPMethod) {
	case "GET", "HEAD", "OPTIONS":
		// Nothing to protect: these change nothing.
		return false
	}
	return true
}

// writeCSRFOnlyCheck emits the session lookup a handler runs for its CSRF token.
// The session itself is not passed on; the handler did not ask for it.
func (w *Writer) writeCSRFOnlyCheck() {
	w.Line(1, "// CSRF protection covers every state-changing action, including")
	w.Line(1, "// the ones that read nothing of the session.")
	w.Line(1, "if _, _, ok := s.ReadSession(w, r); !ok {")
	w.Line(2, "return")
	w.Line(1, "}")
}

// writeAppErrHelpers emits httpErrIntern,
// which answers a request whose handler failed.
//
// PageError500 and RecoverError are separate features and each one applies on its own.
// A page load is answered by the 500 page when the app supplies one.
// A Datastar request is answered by RecoverError when the app defines it,
// because that request expects an event stream rather than a document.
// An app that has only one of the two gets it for the requests it covers,
// and the plain HTTP error for the rest.
func (w *Writer) writeAppErrHelpers(m *model.App, appPkg string) {
	hasPage := m.PageError500 != nil
	hasRecover := m.RecoverError != nil

	if !hasPage && !hasRecover {
		w.Raw(`
func (s *Server) httpErrIntern(
	w http.ResponseWriter, _ *http.Request,
	_ *datastar.ServerSentEventGenerator, msg string, err error,
) {
	s.LogErr(msg, err)
`)
		w.writeHTTPErrFallback()
		w.Raw(`}
`)
		return
	}

	if hasPage {
		// httpErrIntern answers a page load by rendering PageError500.
		// The handler of that page therefore can't report through it.
		w.Raw(`
// httpErrFinal writes the error response without rendering PageError500.
// The PageError500 handler uses it so it can't render itself.
func (s *Server) httpErrFinal(w http.ResponseWriter, msg string, err error) {
	s.LogErr(msg, err)
`)
		w.writeHTTPErrFallback()
		w.Raw(`}
`)
	}

	w.Raw(`
func (s *Server) httpErrIntern(
	w http.ResponseWriter, r *http.Request,
	sse *datastar.ServerSentEventGenerator, msg string, err error,
) {
	s.LogErr(msg, err)
`)
	if hasPage {
		w.Raw(`	if !httpserve.IsDatastarRequest(r) {
		// A page load gets the app's own 500 page, with the status that
		// says what happened. The page's own route serves 200;
		// this is the other way in.
		w.WriteHeader(http.StatusInternalServerError)
		s.handlePageError500GET(w, r)
		return
	}
`)
	}
	if hasRecover {
		w.Raw(`	// The response of a Datastar request is an event stream. Once one is
	// open the status line is gone, which is what committed reports.
	committed := sse != nil
	if sse == nil {
		sse = datastar.NewSSE(w, r, datastar.WithCompression())
		committed = true
	}
	errRecover := s.`)
		w.Raw(appPkg)
		w.Raw(`.RecoverError(`)
		for i, kind := range m.RecoverError.OrderedInputs {
			if i > 0 {
				w.Raw(", ")
			}
			if kind == model.InputKindSSE {
				w.Raw("dpsse.New(sse)")
			} else {
				w.Raw("err")
			}
		}
		w.Raw(`)
	if errRecover == nil {
`)
		if w.prometheus {
			w.Raw(`		prom.InternalErrorRecovered()
`)
		}
		w.Raw(`		return // Feedback delivered gracefully.
	}
	// RecoverError failed — fall back to HTTP error response.
`)
		if w.prometheus {
			w.Raw(`	prom.InternalErrorNotRecovered()
`)
		}
		w.Raw(`	s.Logger().Error("recovering error",
		slog.Any("orig.msg", msg),
		slog.Any("orig.err", err),
		slog.Any("err", errRecover))
	if committed {
		// http.Error would write a status the client already received,
		// and append its text to the event stream the client is reading.
		return
	}
`)
	}
	w.writeHTTPErrFallback()
	w.Raw(`}
`)
}

func (w *Writer) writeRender404(m *model.App, appPkg string) {
	p := m.PageError404

	w.Line(0, "")
	w.Line(0, "func (s *Server) render404(w http.ResponseWriter, r *http.Request) {")
	w.Line(1, "// The URL is claimed by no page. Whatever the app renders for it,")
	w.Line(1, "// the response says so: a cache that stores it and a crawler that")
	w.Line(1, "// reads it both go by the status.")
	w.Line(1, "w.WriteHeader(http.StatusNotFound)")

	h404 := p.GET.Handler
	headNeedsSess := m.GlobalHeadGenerator != nil && m.GlobalHeadGenerator.InputSession
	if h404.InputSession != nil || headNeedsSess {
		w.Line(1, "sess, _, ok := s.ReadSession(w, r)")
		w.Line(1, "if !ok {")
		w.Line(2, "return")
		w.Line(1, "}")
		w.Line(0, "")
	}

	w.writePageConstructorStmt("p", p, appPkg)
	w.Line(0, "")

	// Call GET.
	w.writeGETCall(p, m, appPkg, "render404")

	w.Line(0, "}")
}

func (w *Writer) writePageConstructorStmt(varName string, p *model.Page, appPkg string) {
	w.Byte('\t')
	w.Raw(varName)
	w.Raw(" := ")
	w.Raw(appPkg)
	w.Byte('.')
	w.Raw(p.TypeName)
	w.Raw("{\n")
	w.Line(2, "App: s.app,")
	for _, embed := range p.Embeds {
		w.writeEmbedInitStmt(p, embed, appPkg, 2, nil)
	}
	w.Line(1, "}")
}

func (w *Writer) writeEmbedInitStmt(
	p *model.Page, ap *model.AbstractPage, appPkg string, indent int,
	parent types.Type,
) {
	for range indent {
		w.Byte('\t')
	}
	w.Raw(ap.TypeName)
	w.Raw(": ")
	expr, embedded := w.embedLiteralExpr(p, ap, appPkg, parent)
	w.Raw(expr)
	w.Raw("{\n")
	w.Line(indent+1, "App: s.app,")
	for _, sub := range ap.Embeds {
		w.writeEmbedInitStmt(p, sub, appPkg, indent+1, embedded)
	}
	w.Line(indent, "},")
}

// App-level action handler generation kept here; methodized.

func (w *Writer) writeAppActionHandler(h *model.Handler, m *model.App, appPkg string) {
	w.Line(0, "")
	w.Raw("func (s *Server) handle")
	w.Raw(strings.ToUpper(h.HTTPMethod))
	w.Raw(h.Name)
	w.Raw("(w http.ResponseWriter, r *http.Request) {\n")

	if h.InputSSE != nil || h.InputSignals != nil {
		w.Line(1, "if !s.checkIsDSReq(w, r) {")
		w.Line(2, "return")
		w.Line(1, "}")
		w.Line(0, "")
	}

	// Stateful App-level action: verify the Datapages-Instance header and
	// look up the slot in the map for the referenced state type.
	// The action only succeeds when the calling tab is bound to a page that uses
	// the same state type. Its mutex is taken once the request has been read.
	if h.InputState != nil {
		w.writeVerifyInstanceIDHeader()
		w.writeLookupSlotOrReject(stateTypeRef(m, h.InputState.StateTypeName))
		if h.InputStateID != nil {
			w.writeStateRouteKeyVar()
		}
	}

	// Auth.
	needsToken := h.OutputCloseSession != nil
	headNeedsSess := h.OutputBody != nil && m.GlobalHeadGenerator != nil &&
		m.GlobalHeadGenerator.InputSession
	switch {
	case h.InputSession != nil || needsToken || headNeedsSess:
		// A local nobody reads is a package that does not compile.
		sessVar := "_"
		if h.InputSession != nil || headNeedsSess {
			sessVar = "sess"
		}
		if needsToken {
			w.Linef(1, "%s, sessToken, ok := s.ReadSession(w, r)", sessVar)
		} else {
			w.Linef(1, "%s, _, ok := s.ReadSession(w, r)", sessVar)
		}
		w.Line(1, "if !ok {")
		w.Line(2, "return")
		w.Line(1, "}")
	case needsCSRFOnly(h, m):
		w.writeCSRFOnlyCheck()
	}

	// Build the call.
	w.writeHandlerCallAndOutputs(nil, h, m, appPkg, true)

	w.Line(0, "}")
}

func (w *Writer) writeHandlerCallAndOutputs(
	p *model.Page, h *model.Handler, m *model.App, appPkg string, isAppLevel bool,
) {
	// Body size limit for non-GET actions.
	if h.InputSignals != nil && h.InputSSE == nil {
		w.Line(1, "r.Body = http.MaxBytesReader(w, r.Body, DefaultBodySizeLimit)")
	}

	// Read signals.
	if h.InputSignals != nil {
		w.Raw("\tvar signals ")
		w.Raw(renderSignalsType(h.InputSignals, m))
		w.Byte('\n')
		w.Line(1, "if err := datastar.ReadSignals(r, &"+varSignals+"); err != nil {")
		w.Line(2, `s.httpErrBad(w, "reading signals", err)`)
		w.Line(2, "return")
		w.Line(1, "}")
	}

	// Read query params.
	if h.InputQuery != nil {
		w.writeReadQuery(h.InputQuery, m)
	}

	// Read path params.
	if h.InputPath != nil {
		w.writeReadPath(h.InputPath, m)
	}

	// The request is read; claim the state for the duration of the handler.
	// Before the SSE generator, which commits the response headers and would
	// leave the rejection below nowhere to go.
	if h.InputState != nil {
		w.writeLockSlotOrReject()
	}

	// Dispatch closures.
	w.writeDispatchers(h, "dispatch", "r.Context()")

	// SSE for actions that take it.
	if h.InputSSE != nil && !isAppLevel {
		w.Line(0, "")
		w.Line(1, "sse := datastar.NewSSE(w, r, datastar.WithCompression())")
	}

	// Page constructor (for page actions).
	if p != nil {
		w.writePageConstructorStmt("p", p, appPkg)
	}

	// Build the actual method call.
	w.writeMethodCall(p, h, m, isAppLevel)
}

func (w *Writer) writeMethodCall(
	p *model.Page, h *model.Handler, m *model.App, isAppLevel bool,
) {
	// Build output variable list in user-defined order.
	outs := handlerOutputVars(h)

	// Build input args in user-defined order.
	args := handlerInputArgs(h, isAppLevel, "dispatch")

	// Build the call expression.
	receiver := "p"
	if isAppLevel {
		receiver = "s.app"
	}
	methodName := h.HTTPMethod + h.Name

	if len(outs) == 0 {
		// Void return or only error.
		if h.OutputErr != nil {
			w.Raw("\tif err := ")
			w.writeCallExpr(receiver, methodName, args)
			w.Raw("; err != nil {\n")
			w.Raw("\t\ts.httpErrIntern(w, r, nil, \"handling action ")
			w.Raw(actionOwnerName(p, isAppLevel))
			w.Byte('.')
			w.Raw(h.Name)
			w.Raw("\", err)\n")
			w.Line(1, "}")
		} else {
			w.Byte('\t')
			w.writeCallExpr(receiver, methodName, args)
			w.Byte('\n')
		}
		return
	}

	w.Byte('\t')
	w.writeCommaSep(outs)
	w.Raw(" := ")
	w.writeCallExpr(receiver, methodName, args)
	w.Byte('\n')

	if h.OutputErr != nil {
		sseRef := "nil"
		if h.InputSSE != nil && !isAppLevel {
			sseRef = "sse"
		}
		w.Line(1, "if err != nil {")
		w.Raw("\t\ts.httpErrIntern(w, r, ")
		w.Raw(sseRef)
		w.Raw(", \"handling ")
		w.Raw(handlerKind(h))
		if handlerKind(h) != "" {
			w.Byte(' ')
		}
		w.Raw(actionOwnerName(p, isAppLevel))
		w.Byte('.')
		w.Raw(h.Name)
		w.Raw("\", err)\n")
		w.Line(2, "return")
		w.Line(1, "}")
	}

	// Close session.
	if h.OutputCloseSession != nil {
		w.Raw("\tif ")
		w.Raw(outputVar(h.OutputCloseSession))
		w.Raw(" {\n")
		w.Line(2, "if err := s.CloseSession(w, r, sessToken); err != nil {")
		w.Line(3, `s.httpErrIntern(w, r, nil, "removing session", err)`)
		w.Line(3, "return")
		w.Line(2, "}")
		w.Line(1, "}")
	}

	// New session.
	if h.OutputNewSession != nil {
		w.Raw("\tif j := ")
		w.Raw(outputVar(h.OutputNewSession))
		w.Raw("; j.UserID != \"\" {\n")
		w.Raw("\t\tif err := s.CreateSession(w, r, ")
		w.Raw(outputVar(h.OutputNewSession))
		w.Raw("); err != nil {\n")
		w.Line(3, `s.httpErrIntern(w, r, nil, "creating session", err)`)
		w.Line(2, "}")
		w.Line(1, "}")
	}

	// Redirect.
	if h.OutputRedirect != nil {
		w.Raw("\tif httpserve.Redirect(w, r, ")
		w.Raw(outputVar(h.OutputRedirect))
		w.Raw(") {\n")
		w.Line(2, "return")
		w.Line(1, "}")
	}

	// Render body (if action returns templ.Component).
	if h.OutputBody != nil {
		ownerName := actionOwnerName(p, isAppLevel)

		if m.GlobalHeadGenerator != nil {
			w.writeGenericHeadCall(m.GlobalHeadGenerator, hasSessionInput(h))
		}

		w.Line(1, "if err := s.writeHTML(")
		w.Raw("\t\tw, r, ")
		if m.Session != nil {
			sessArg := "sess"
			headNeedsSession := m.GlobalHeadGenerator != nil &&
				m.GlobalHeadGenerator.InputSession
			if !hasSessionInput(h) && !headNeedsSession {
				sessArg = w.sessionType + "{}"
			}
			w.Raw(sessArg)
			w.Raw(", ")
		}
		if m.GlobalHeadGenerator != nil {
			w.Raw("genericHead, nil, ")
		} else {
			w.Raw("nil, ")
		}
		w.Raw(outputVar(h.OutputBody.Output))
		w.Raw(", nil, nil,\n")
		w.Line(1, "); err != nil {")
		w.Raw("\t\ts.LogErr(\"rendering response of ")
		w.Raw(ownerName)
		w.Byte('.')
		w.Raw(h.HTTPMethod)
		w.Raw(h.Name)
		w.Raw("\", err)\n")
		w.Line(2, "return")
		w.Line(1, "}")
	}
}

// writeDispatchers emits one dispatcher value per datapages.Dispatcher parameter
// of the handler. prefix names them apart when a generated function holds the
// dispatchers of more than one handler, as the stream handler does.
// ctxExpr is the context Dispatch publishes with.
func (w *Writer) writeDispatchers(h *model.Handler, prefix, ctxExpr string) {
	for _, d := range h.InputDispatches {
		if !slices.Contains(w.dispatchedEvents, d.EventTypeName) {
			w.dispatchedEvents = append(w.dispatchedEvents, d.EventTypeName)
		}
		w.Line(0, "")
		w.Byte('\t')
		w.Raw(dispatchVarName(prefix, d.EventTypeName))
		w.Raw(" := ")
		w.Raw(dispatcherTypeName(d.EventTypeName))
		w.Raw("{s: s, ctx: ")
		w.Raw(ctxExpr)
		w.Raw("}\n")
	}
}

// writeDispatcherTypes emits the datapages.Dispatcher implementation of every
// event a handler dispatches. It marshals the event and publishes it to every
// subject its subject fields expand into.
func (w *Writer) writeDispatcherTypes(appPkg string) {
	for _, evName := range w.dispatchedEvents {
		w.writeDispatcherType(evName, appPkg)
	}
}

func (w *Writer) writeDispatcherType(evName, appPkg string) {
	ev := w.eventMap[evName]
	typeName := dispatcherTypeName(evName)
	eventType := appPkg + "." + evName

	w.Line(0, "")
	w.Raw("type ")
	w.Raw(typeName)
	w.Raw(" struct {\n")
	w.Line(1, "s   *Server")
	w.Line(1, "ctx context.Context")
	w.Line(0, "}")

	w.Line(0, "")
	w.Raw("func (d ")
	w.Raw(typeName)
	w.Raw(") Dispatch(e ")
	w.Raw(eventType)
	w.Raw(") error {\n")
	w.Line(1, "return d.DispatchCtx(d.ctx, e)")
	w.Line(0, "}")

	w.Line(0, "")
	w.Raw("func (d ")
	w.Raw(typeName)
	w.Raw(") DispatchCtx(\n")
	w.Line(1, "ctx context.Context, e "+eventType+",")
	w.Line(0, ") error {")

	if ev != nil && ev.HasSubjectFields() {
		// Guard before any work: a value carrying a separator or a wildcard
		// makes a subject of a different shape,
		// which every subscription then misses in silence.
		for _, sf := range ev.SubjectFields {
			w.Raw("\tif !subject.IsToken(string(e.")
			w.Raw(sf.FieldName)
			w.Raw(")) {\n")
			w.Line(2, "return fmt.Errorf(")
			w.Raw("\t\t\t\"")
			w.Raw(evName)
			w.Byte('.')
			w.Raw(sf.FieldName)
			w.Raw(" must be a non-empty subject token, received %q\",\n")
			w.Raw("\t\t\te.")
			w.Raw(sf.FieldName)
			w.Raw(")\n")
			w.Line(1, "}")
		}
	}

	w.Line(1, "j, err := json.Marshal(e)")
	w.Line(1, "if err != nil {")
	w.Raw("\t\treturn fmt.Errorf(\"marshaling ")
	w.Raw(evName)
	w.Raw(" JSON: %w\", err)\n")
	w.Line(1, "}")

	if ev != nil && ev.HasSubjectFields() {
		// Every segment carries one value, so the subject is a plain
		// concatenation of the base subject and the fields, in field order.
		w.Raw("\tsubj := ")
		w.writeQuoted(ev.Subject + ".")
		for i, sf := range ev.SubjectFields {
			if i > 0 {
				w.Raw(` + "." + `)
			} else {
				w.Raw(" + ")
			}
			w.Raw("string(e.")
			w.Raw(sf.FieldName)
			w.Byte(')')
		}
		w.Byte('\n')
		w.Raw("\terr = d.s.messageBroker.Publish(")
		w.Raw("ctx, d.s.messageBrokerMetrics, subj, j)\n")
		w.Line(1, "if err != nil {")
		w.Raw("\t\treturn fmt.Errorf(\"publishing subject %q: %w\", subj, err)\n")
		w.Line(1, "}")
	} else if ev != nil {
		w.Raw("\terr = d.s.messageBroker.Publish(ctx, d.s.messageBrokerMetrics, ")
		w.Raw(evSubjConst(ev))
		w.Raw(", j)\n")
		w.Line(1, "if err != nil {")
		w.Raw("\t\treturn fmt.Errorf(\"publishing subject %q: %w\", ")
		w.Raw(evSubjConst(ev))
		w.Raw(", err)\n")
		w.Line(1, "}")
	}

	w.Line(1, "return nil")
	w.Line(0, "}")
}

// Handler inputs are carried by datapages.Path, datapages.Query and
// datapages.Signals, so generated code populates the Values field of each.
const (
	varPath    = "path.Values"
	varQuery   = "query.Values"
	varSignals = "signals.Values"
)

func renderSignalsType(input *model.Input, m *model.App) string {
	return "datapages.Signals[" + renderValuesType(input, m) + "]"
}

func renderQueryType(input *model.Input, m *model.App) string {
	return "datapages.Query[" + renderValuesType(input, m) + "]"
}

func renderPathType(input *model.Input, m *model.App) string {
	return "datapages.Path[" + renderValuesType(input, m) + "]"
}

// renderValuesType renders the Values type argument of a wrapped input.
func renderValuesType(input *model.Input, m *model.App) string {
	if isNamedType(input.Type) {
		return renderType(input.Type)
	}
	return renderAnonStructType(input.Type, m.Fset)
}

func handlerKind(h *model.Handler) string {
	if h.HTTPMethod == "" || h.HTTPMethod == "GET" {
		return ""
	}
	return "action"
}

func actionOwnerName(p *model.Page, isAppLevel bool) string {
	if isAppLevel {
		return "App"
	}
	if p != nil {
		return p.TypeName
	}
	return "App"
}

// writeGETCall generates the GET method call and HTML rendering for a page.
func (w *Writer) writeGETCall(
	p *model.Page, m *model.App, appPkg string, context string,
) {
	if p.GET == nil || p.GET.OutputBody == nil {
		return
	}
	h := p.GET.Handler

	// Build output list.
	var outsBuf [8]string
	outs := outsBuf[:0]
	if p.GET.OutputBody != nil {
		outs = append(outs, outputVar(p.GET.OutputBody.Output))
	}
	if p.GET.OutputHead != nil {
		outs = append(outs, outputVar(p.GET.OutputHead.Output))
	}
	if h.OutputRedirect != nil {
		outs = append(outs, outputVar(h.OutputRedirect))
	}
	if h.OutputDisableRefresh != nil {
		outs = append(outs, outputVar(h.OutputDisableRefresh))
	}
	if h.OutputEnableBgStream != nil {
		outs = append(outs, outputVar(h.OutputEnableBgStream))
	}
	if h.OutputErr != nil {
		outs = append(outs, "err")
	}

	// Build input args in user-defined order.
	args := handlerInputArgs(h, false, "dispatch")

	w.Byte('\t')
	w.writeCommaSep(outs)
	w.Raw(" := ")
	w.writeCallExpr("p", "GET", args)
	w.Byte('\n')

	if h.OutputErr != nil {
		w.Line(1, "if err != nil {")
		w.Raw("\t\ts.httpErrIntern(w, r, nil, \"handling ")
		w.Raw(p.TypeName)
		w.Raw(".GET\", err)\n")
		w.Line(2, "return")
		w.Line(1, "}")
	}

	// Redirect.
	if h.OutputRedirect != nil {
		w.Raw("\tif httpserve.Redirect(w, r, ")
		w.Raw(outputVar(h.OutputRedirect))
		w.Raw(") {\n")
		w.Line(2, "return")
		w.Line(1, "}")
	}

	// Generic head.
	if m.GlobalHeadGenerator != nil {
		w.writeGenericHeadCall(m.GlobalHeadGenerator, h.InputSession != nil)
	}

	// Body attrs - simple for render404/error pages.
	w.Line(0, "")
	w.Line(1, "bodyAttrs := func(w http.ResponseWriter) {")
	w.Line(2, "httpserve.WriteReloadOnVisibility(w)")
	w.Line(1, "}")

	headArg := "nil"
	if p.GET.OutputHead != nil {
		headArg = outputVar(p.GET.OutputHead.Output)
	}

	w.Line(1, "if err := s.writeHTML(")
	w.Raw("\t\tw, r, ")
	if m.Session != nil {
		sessArg := "sess"
		headNeedsSession := m.GlobalHeadGenerator != nil &&
			m.GlobalHeadGenerator.InputSession
		if p.PageSpecialization == model.PageTypeError500 ||
			(p.PageSpecialization == model.PageTypeError404 &&
				context == "render404" && !headNeedsSession) {
			sessArg = w.sessionType + "{}"
		}
		w.Raw(sessArg)
		w.Raw(", ")
	}
	if m.GlobalHeadGenerator != nil {
		w.Raw("genericHead, ")
	}
	w.Raw(headArg)
	w.Raw(", body, bodyAttrs, nil,\n")
	w.Line(1, "); err != nil {")
	w.Raw("\t\ts.LogErr(\"rendering ")
	w.Raw(p.TypeName)
	w.Raw("\", err)\n")
	w.Line(2, "return")
	w.Line(1, "}")
}
