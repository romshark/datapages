// App-level action handler generation kept here; methodized.

func (w *Writer) writeAppActionHandler(h *model.Handler, m *model.App, appPkg string) {
	w.Line(0, "")
	w.Raw("func (s *Server) handle")
	w.Raw(strings.ToUpper(h.HTTPMethod))
	w.Raw(h.Name)
	w.Raw("(w http.ResponseWriter, r *http.Request) {\n")

	if h.InputSSE != nil || h.InputSignals != nil {
		w.Line(1, "if !s.CheckDatastarRequest(w, r) {")
		w.Line(2, "return")
		w.Line(1, "}")
		w.Line(0, "")
	}

	// Stateful App-level action: verify the Datapages-Instance header and
	// look up the slot in the map for the referenced state type.
	// The action only succeeds when the calling tab is bound to a page that uses
	// the same state type. Its mutex is taken once the request has been read.
	if h.InputState != nil {
		w.writeVerifyInstanceIDHeader()
		w.writeLookupSlotOrReject(stateTypeRef(m, h.InputState.StateTypeName))
		if h.InputStateID != nil {
			w.writeStateRouteKeyVar()
		}
	}

	// Auth.
	needsToken := h.OutputCloseSession != nil
	headNeedsSess := h.OutputBody != nil && m.GlobalHeadGenerator != nil &&
		m.GlobalHeadGenerator.InputSession
	switch {
	case h.InputSession != nil || needsToken || headNeedsSess:
		// A local nobody reads is a package that does not compile.
		sessVar := "_"
		if h.InputSession != nil || headNeedsSess {
			sessVar = "sess"
		}
		if needsToken {
			w.Linef(1, "%s, sessToken, ok := s.ReadSession(w, r)", sessVar)
		} else {
			w.Linef(1, "%s, _, ok := s.ReadSession(w, r)", sessVar)
		}
		w.Line(1, "if !ok {")
		w.Line(2, "return")
		w.Line(1, "}")
	case needsCSRFOnly(h, m):
		w.writeCSRFOnlyCheck()
	}

	// Build the call.
	w.writeHandlerCallAndOutputs(nil, h, m, appPkg, true)

	w.Line(0, "}")
}

func (w *Writer) writeHandlerCallAndOutputs(
	p *model.Page, h *model.Handler, m *model.App, appPkg string, isAppLevel bool,
) {
	// Body size limit for non-GET actions.
	if h.InputSignals != nil {
		w.Line(1, "r.Body = http.MaxBytesReader(w, r.Body, DefaultBodySizeLimit)")
	}

	// Read signals.
	if h.InputSignals != nil {
		w.Raw("\tvar signals ")
		w.Raw(renderSignalsType(h.InputSignals, m))
		w.Byte('\n')
		w.Line(1, "if err := datastar.ReadSignals(r, &"+varSignals+"); err != nil {")
		w.Line(2, `s.HTTPErrBad(w, "reading signals", err)`)
		w.Line(2, "return")
		w.Line(1, "}")
	}

	// Read query params.
	if h.InputQuery != nil {
		w.writeReadQuery(h.InputQuery, m)
	}

	// Read path params.
	if h.InputPath != nil {
		w.writeReadPath(h.InputPath, m, h.Route)
	}

	// The request is read; claim the state for the duration of the handler.
	// Before the SSE generator, which commits the response headers and would
	// leave the rejection below nowhere to go.
	if h.InputState != nil {
		w.writeLockSlotOrReject()
	}

	// Dispatch closures.
	w.writeDispatchers(h, "dispatch", "r.Context()")

	// SSE for actions that take it.
	if h.InputSSE != nil && !isAppLevel {
		w.Line(0, "")
		w.Line(1, "sse := datastar.NewSSE(w, r, datastar.WithCompression())")
	}

	// Page constructor (for page actions).
	if p != nil {
		w.writePageConstructorStmt("p", p, appPkg)
	}

	// Build the actual method call.
	w.writeMethodCall(p, h, m, isAppLevel)
}

func (w *Writer) writeMethodCall(
	p *model.Page, h *model.Handler, m *model.App, isAppLevel bool,
) {
	// Build output variable list in user-defined order.
	outs := handlerOutputVars(h)

	// Build input args in user-defined order.
	args := handlerInputArgs(h, isAppLevel, "dispatch", w.appPkgQual)

	// Build the call expression.
	receiver := "p"
	if isAppLevel {
		receiver = "s.app"
	}
	methodName := h.HTTPMethod + h.Name

	if len(outs) == 0 {
		// Void return or only error.
		if h.OutputErr != nil {
			w.Raw("\tif err := ")
			w.writeCallExpr(receiver, methodName, args)
			w.Raw("; err != nil {\n")
			w.Raw("\t\ts.httpErrIntern(w, r, nil, \"handling action ")
			w.Raw(actionOwnerName(p, isAppLevel))
			w.Byte('.')
			w.Raw(h.Name)
			w.Raw("\", err)\n")
			w.Line(1, "}")
		} else {
			w.Byte('\t')
			w.writeCallExpr(receiver, methodName, args)
			w.Byte('\n')
		}
		return
	}

	w.Byte('\t')
	w.writeCommaSep(outs)
	w.Raw(" := ")
	w.writeCallExpr(receiver, methodName, args)
	w.Byte('\n')

	if h.OutputErr != nil {
		sseRef := "nil"
		if h.InputSSE != nil && !isAppLevel {
			sseRef = "sse"
		}
		w.Line(1, "if err != nil {")
		w.Raw("\t\ts.httpErrIntern(w, r, ")
		w.Raw(sseRef)
		w.Raw(", \"handling ")
		w.Raw(handlerKind(h))
		if handlerKind(h) != "" {
			w.Byte(' ')
		}
		w.Raw(actionOwnerName(p, isAppLevel))
		w.Byte('.')
		w.Raw(h.Name)
		w.Raw("\", err)\n")
		w.Line(2, "return")
		w.Line(1, "}")
	}

	// Close session.
	if h.OutputCloseSession != nil {
		w.Raw("\tif ")
		w.Raw(outputVar(h.OutputCloseSession))
		w.Raw(" {\n")
		w.Line(2, "if err := s.CloseSession(w, r, sessToken); err != nil {")
		w.Line(3, `s.httpErrIntern(w, r, nil, "removing session", err)`)
		w.Line(3, "return")
		w.Line(2, "}")
		w.Line(1, "}")
	}

	// New session.
	if h.OutputNewSession != nil {
		w.Raw("\tif j := ")
		w.Raw(outputVar(h.OutputNewSession))
		w.Raw("; j.UserID != \"\" {\n")
		w.Raw("\t\tif err := s.CreateSession(w, r, ")
		w.Raw(outputVar(h.OutputNewSession))
		w.Raw("); err != nil {\n")
		w.Line(3, `s.httpErrIntern(w, r, nil, "creating session", err)`)
		w.Line(2, "}")
		w.Line(1, "}")
	}

	// Redirect.
	if h.OutputRedirect != nil {
		w.Raw("\tif httpserve.Redirect(w, r, ")
		w.Raw(outputVar(h.OutputRedirect))
		w.Raw(") {\n")
		w.Line(2, "return")
		w.Line(1, "}")
	}

	// Render body (if action returns templ.Component).
	if h.OutputBody != nil {
		ownerName := actionOwnerName(p, isAppLevel)

		if m.GlobalHeadGenerator != nil {
			w.writeGenericHeadCall(m.GlobalHeadGenerator, hasSessionInput(h))
		}

		w.Line(1, "if err := s.writeHTML(")
		w.Raw("\t\tw, r, ")
		if m.Session != nil {
			sessArg := "sess"
			headNeedsSession := m.GlobalHeadGenerator != nil &&
				m.GlobalHeadGenerator.InputSession
			if !hasSessionInput(h) && !headNeedsSession {
				sessArg = w.sessionType + "{}"
			}
			w.Raw(sessArg)
			w.Raw(", ")
		}
		if m.GlobalHeadGenerator != nil {
			w.Raw("genericHead, nil, ")
		} else {
			w.Raw("nil, ")
		}
		w.Raw(outputVar(h.OutputBody.Output))
		w.Raw(", nil, nil,\n")
		w.Line(1, "); err != nil {")
		w.Raw("\t\ts.LogErr(\"rendering response of ")
		w.Raw(ownerName)
		w.Byte('.')
		w.Raw(h.HTTPMethod)
		w.Raw(h.Name)
		w.Raw("\", err)\n")
		w.Line(2, "return")
		w.Line(1, "}")
	}
}

// writeDispatchers emits one dispatcher value per datapages.Dispatcher parameter
// of the handler. prefix names them apart when a generated function holds the
// dispatchers of more than one handler, as the stream handler does.
// ctxExpr is the context Dispatch publishes with.
func (w *Writer) writeDispatchers(h *model.Handler, prefix, ctxExpr string) {
	for _, d := range h.InputDispatches {
		if !slices.Contains(w.dispatchedEvents, d.EventTypeName) {
			w.dispatchedEvents = append(w.dispatchedEvents, d.EventTypeName)
		}
		w.Line(0, "")
		w.Byte('\t')
		w.Raw(dispatchVarName(prefix, d.EventTypeName))
		w.Raw(" := ")
		w.Raw(dispatcherTypeName(d.EventTypeName))
		w.Raw("{s: s, ctx: ")
		w.Raw(ctxExpr)
		w.Raw("}\n")
	}
}

// writeDispatcherTypes emits the datapages.Dispatcher implementation of every
// event a handler dispatches. It marshals the event and publishes it to every
// subject its subject fields expand into.
func (w *Writer) writeDispatcherTypes(appPkg string) {
	for _, evName := range w.dispatchedEvents {
		w.writeDispatcherType(evName, appPkg)
	}
}

func (w *Writer) writeDispatcherType(evName, appPkg string) {
	ev := w.eventMap[evName]
	typeName := dispatcherTypeName(evName)
	eventType := appPkg + "." + evName

	w.Line(0, "")
	w.Raw("type ")
	w.Raw(typeName)
	w.Raw(" struct {\n")
	w.Line(1, "s   *Server")
	w.Line(1, "ctx context.Context")
	w.Line(0, "}")

	w.Line(0, "")
	w.Raw("func (d ")
	w.Raw(typeName)
	w.Raw(") Dispatch(e ")
	w.Raw(eventType)
	w.Raw(") error {\n")
	w.Line(1, "return d.DispatchCtx(d.ctx, e)")
	w.Line(0, "}")

	w.Line(0, "")
	w.Raw("func (d ")
	w.Raw(typeName)
	w.Raw(") DispatchCtx(\n")
	w.Line(1, "ctx context.Context, e "+eventType+",")
	w.Line(0, ") error {")

	if ev != nil && ev.HasSubjectFields() {
		// Guard before any work: a value carrying a separator or a wildcard
		// makes a subject of a different shape,
		// which every subscription then misses in silence.
		for _, sf := range ev.SubjectFields {
			w.Raw("\tif e.")
			w.Raw(sf.FieldName)
			w.Raw(" == \"\" {\n")
			w.Raw("\t\treturn errors.New(\"")
			w.Raw(evName)
			w.Byte('.')
			w.Raw(sf.FieldName)
			w.Raw(" must not be empty\")\n")
			w.Line(1, "}")
		}
	}

	w.Line(1, "j, err := json.Marshal(e)")
	w.Line(1, "if err != nil {")
	w.Raw("\t\treturn fmt.Errorf(\"marshaling ")
	w.Raw(evName)
	w.Raw(" JSON: %w\", err)\n")
	w.Line(1, "}")

	if ev != nil && ev.HasSubjectFields() {
		// Every segment carries one value, so the subject is a plain
		// concatenation of the base subject and the fields, in field order.
		w.Raw("\tsubj := ")
		w.writeQuoted(ev.Subject + ".")
		for i, sf := range ev.SubjectFields {
			if i > 0 {
				w.Raw(` + "." + `)
			} else {
				w.Raw(" + ")
			}
			w.Raw("subject.Encode(string(e.")
			w.Raw(sf.FieldName)
			w.Raw("))")
		}
		w.Byte('\n')
		w.Raw("\terr = d.s.messageBroker.Publish(")
		w.Raw("ctx, d.s.messageBrokerMetrics, subj, j)\n")
		w.Line(1, "if err != nil {")
		w.Raw("\t\treturn fmt.Errorf(\"publishing subject %q: %w\", subj, err)\n")
		w.Line(1, "}")
	} else if ev != nil {
		w.Raw("\terr = d.s.messageBroker.Publish(ctx, d.s.messageBrokerMetrics, ")
		w.Raw(evSubjConst(ev))
		w.Raw(", j)\n")
		w.Line(1, "if err != nil {")
		w.Raw("\t\treturn fmt.Errorf(\"publishing subject %q: %w\", ")
		w.Raw(evSubjConst(ev))
		w.Raw(", err)\n")
		w.Line(1, "}")
	}

	w.Line(1, "return nil")
	w.Line(0, "}")
}

// Handler inputs are carried by datapages.Path, datapages.Query and
// datapages.Signals, so generated code populates the Values field of each.
const (
	varPath    = "path.Values"
	varQuery   = "query.Values"
	varSignals = "signals.Values"
)

func renderSignalsType(input *model.Input, m *model.App) string {
	return "datapages.Signals[" + renderValuesType(input, m) + "]"
}

func renderQueryType(input *model.Input, m *model.App) string {
	return "datapages.Query[" + renderValuesType(input, m) + "]"
}

func renderPathType(input *model.Input, m *model.App) string {
	return "datapages.Path[" + renderValuesType(input, m) + "]"
}

// renderValuesType renders the Values type argument of a wrapped input.
func renderValuesType(input *model.Input, m *model.App) string {
	if isNamedType(input.Type) {
		return renderType(input.Type)
	}
	return renderAnonStructType(input.Type, m.Fset)
}

func handlerKind(h *model.Handler) string {
	if h.HTTPMethod == "" || h.HTTPMethod == "GET" {
		return ""
	}
	return "action"
}

func actionOwnerName(p *model.Page, isAppLevel bool) string {
	if isAppLevel {
		return "App"
	}
	if p != nil {
		return p.TypeName
	}
	return "App"
}

// writeGETCall generates the GET method call and HTML rendering for a page.
func (w *Writer) writeGETCall(
	p *model.Page, m *model.App, appPkg string, context string,
) {
	if p.GET == nil || p.GET.OutputBody == nil {
		return
	}
	h := p.GET.Handler

	// Build output list.
	var outsBuf [8]string
	outs := outsBuf[:0]
	if p.GET.OutputBody != nil {
		outs = append(outs, outputVar(p.GET.OutputBody.Output))
	}
	if p.GET.OutputHead != nil {
		outs = append(outs, outputVar(p.GET.OutputHead.Output))
	}
	if h.OutputRedirect != nil {
		outs = append(outs, outputVar(h.OutputRedirect))
	}
	if h.OutputDisableRefresh != nil {
		outs = append(outs, outputVar(h.OutputDisableRefresh))
	}
	if h.OutputEnableBgStream != nil {
		outs = append(outs, outputVar(h.OutputEnableBgStream))
	}
	if h.OutputErr != nil {
		outs = append(outs, "err")
	}

	// Build input args in user-defined order.
	args := handlerInputArgs(h, false, "dispatch", w.appPkgQual)

	w.Byte('\t')
	w.writeCommaSep(outs)
	w.Raw(" := ")
	w.writeCallExpr("p", "GET", args)
	w.Byte('\n')

	if h.OutputErr != nil {
		w.Line(1, "if err != nil {")
		w.Raw("\t\ts.httpErrIntern(w, r, nil, \"handling ")
		w.Raw(p.TypeName)
		w.Raw(".GET\", err)\n")
		w.Line(2, "return")
		w.Line(1, "}")
	}

	// Redirect.
	if h.OutputRedirect != nil {
		w.Raw("\tif httpserve.Redirect(w, r, ")
		w.Raw(outputVar(h.OutputRedirect))
		w.Raw(") {\n")
		w.Line(2, "return")
		w.Line(1, "}")
	}

	// Generic head.
	if m.GlobalHeadGenerator != nil {
		w.writeGenericHeadCall(m.GlobalHeadGenerator, h.InputSession != nil)
	}

	// Body attrs - simple for render404/error pages.
	w.Line(0, "")
	w.Line(1, "bodyAttrs := func(w http.ResponseWriter) {")
	w.Line(2, "httpserve.WriteReloadOnVisibility(w)")
	w.Line(1, "}")

	headArg := "nil"
	if p.GET.OutputHead != nil {
		headArg = outputVar(p.GET.OutputHead.Output)
	}

	w.Line(1, "if err := s.writeHTML(")
	w.Raw("\t\tw, r, ")
	if m.Session != nil {
		sessArg := "sess"
		headNeedsSession := m.GlobalHeadGenerator != nil &&
			m.GlobalHeadGenerator.InputSession
		if p.PageSpecialization == model.PageTypeError500 ||
			(p.PageSpecialization == model.PageTypeError404 &&
				context == "render404" && !headNeedsSession) {
			sessArg = w.sessionType + "{}"
		}
		w.Raw(sessArg)
		w.Raw(", ")
	}
	if m.GlobalHeadGenerator != nil {
		w.Raw("genericHead, ")
	}
	w.Raw(headArg)
	w.Raw(", body, bodyAttrs, nil,\n")
	w.Line(1, "); err != nil {")
	w.Raw("\t\ts.LogErr(\"rendering ")
	w.Raw(p.TypeName)
	w.Raw("\", err)\n")
	w.Line(2, "return")
	w.Line(1, "}")
}
