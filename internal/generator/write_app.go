func (w *Writer) writeEventSubjectConsts(events []*model.Event) {
	// EvSubj* constants (subscription subjects with wildcards for prefixed events).
	w.Line(0, "")
	w.Line(0, "const (")

	// Private events first.
	for _, e := range events {
		if e.IsPrivate() {
			w.Byte('\t')
			w.Raw(evSubjConst(e))
			w.Raw(" = ")
			w.writeQuoted(evSubjValue(e))
			w.Byte('\n')
		}
	}

	w.Line(0, "")
	w.Line(1, "// Public events:")
	w.Line(0, "")

	for _, e := range events {
		if !e.IsPrivate() {
			w.Byte('\t')
			w.Raw(evSubjConst(e))
			w.Raw(" = ")
			w.writeQuoted(evSubjValue(e))
			w.Byte('\n')
		}
	}

	w.Line(0, ")")

	// EvSubjPref* constants (prefix for matching private and signal-scoped events).
	hasPrefixed := false
	for _, e := range events {
		if e.IsPrivate() || e.IsSignalScoped() {
			hasPrefixed = true
			break
		}
	}
	if hasPrefixed {
		w.Line(0, "")
		w.Line(0, "const (")
		for _, e := range events {
			if e.IsPrivate() || e.IsSignalScoped() {
				w.Byte('\t')
				w.Raw(evSubjPrefConst(e))
				w.Raw(" = ")
				w.writeQuoted(evSubjPrefValue(e))
				w.Byte('\n')
			}
		}
		w.Line(0, ")")
	}
}

