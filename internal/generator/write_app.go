var appStaticContent2 string

// WriteApp generates code for the generated root package and appends it to buffer.
// pkgName is the Go package name (e.g. "datapagesgen").
func (w *Writer) WriteApp(pkgName string, m *model.App) {
	appPkg := appPkgQualifier(m)
	w.appPkgQual = appPkg
	w.buildEventMap(m.Events)
	w.usage = computeAppUsage(m)
	w.setSessionType(m)

	w.writeAppHeader(pkgName, m.PkgPath, needsJSON(m))
	w.Raw(appStaticContent)
	if w.prometheus {
		w.Raw(appStaticPromContent)
	}
	w.Raw(appStaticContent2)
	if w.usage.auth && w.usage.hasSession {
		w.writeAppCheckCSRF()
	}
	w.writeAppWriteHTML(m)
	if w.usage.stream {
		w.writeAppHandleStreamRequest()
	}
	w.writeAppServerStruct(appPkg)
	w.writeAppInit(appPkg)
	w.writeEventSubjectConsts(m.Events)
	w.writeMessageBrokerStreamSubjects(m.Events)
	w.writeEvSubjPageFuncs(m.Pages)
	if w.prometheus {
		w.writeBrokerSubjectKind(m.Events)
	}
	w.writeStateRuntime(m, appPkg)
	w.writeSetupHandlers(m)
	w.writeAppErrHelpers(m, appPkg)

	if m.PageError404 != nil &&
		m.PageError404.GET != nil && m.PageError404.GET.OutputBody != nil {
		w.writeRender404(m, appPkg)
	}

	// App-level action handlers.
	for _, h := range m.Actions {
		w.writeAppActionHandler(h, m, appPkg)
	}

	// Per-page handlers.
	for _, p := range m.Pages {
		if p.GET != nil && p.GET.OutputBody != nil {
			w.writePageGETHandler(p, m, appPkg)
		}
		if pageHasStream(p) {
			w.writePageGETStreamHandler(p, m, appPkg)
			if pageHasAnonStream(p, w.eventMap) {
				w.writePageGETStreamAnonHandler(p, m, appPkg)
			}
		}
		for _, h := range p.Actions {
			w.writePageActionHandler(p, h, m, appPkg)
		}
	}

	w.writeDispatcherTypes(appPkg)
}

func needsJSON(m *model.App) bool {
	for _, h := range m.Actions {
		if len(h.InputDispatches) > 0 {
			return true
		}
	}
	for _, p := range m.Pages {
		if len(p.EventHandlers) > 0 {
			return true
		}
		for _, h := range []*model.Handler{p.StreamOpen, p.StreamClose} {
			if h != nil && len(h.InputDispatches) > 0 {
				return true
			}
		}
		for _, h := range p.Actions {
			if len(h.InputDispatches) > 0 {
				return true
			}
		}
	}
	return false
}

func (w *Writer) writeAppHeader(pkgName string, appPkgPath string, jsonImport bool) {
	w.Line(0, "// Code generated by github.com/romshark/datapages; DO NOT EDIT.")
	w.Line(0, "")
	w.Linef(0, "package %s", pkgName)
	w.Line(0, "")
	w.Line(0, "import (")
	w.Line(1, `"bufio"`)
	w.Line(1, `"context"`)
	if jsonImport {
		w.Line(1, `"encoding/json"`)
	}
	w.Line(1, `"errors"`)
	w.Line(1, `"fmt"`)
	w.Line(1, `"io"`)
	w.Line(1, `"log/slog"`)
	w.Line(1, `"net"`)
	w.Line(1, `"net/http"`)
	w.Line(1, `"os"`)
	if w.usage.stream {
		w.Line(1, `"runtime/debug"`)
	}
	w.Line(1, `"slices"`)
	w.Line(1, `"strconv"`)
	w.Line(1, `"strings"`)
	w.Line(1, `"sync"`)
	if w.usage.stream {
		w.Line(1, `"sync/atomic"`)
	}
	w.Line(1, `"time"`)
	if w.usage.stateRuntime {
		w.Line(1, `"crypto/hmac"`)
		w.Line(1, `"crypto/rand"`)
		w.Line(1, `"crypto/sha256"`)
		w.Line(1, `"encoding/base64"`)
		w.Line(1, `"hash/maphash"`)
	}
	w.Line(0, "")
	w.Line(1, `"github.com/a-h/templ"`)
	// Always needed: writeHTML renders datapages.Component values.
	w.Line(1, `"github.com/romshark/datapages"`)
	w.Line(1, `"github.com/romshark/datapages/modules/csrf"`)
	w.Line(1, `"github.com/romshark/datapages/modules/messaging"`)
	w.Line(1, `"github.com/romshark/datapages/modules/sessions"`)
	w.Line(1, `"github.com/romshark/datapages/runtime/auth"`)
	w.Line(1, `"github.com/romshark/datapages/runtime/htmlattr"`)
	w.Line(1, `"github.com/romshark/datapages/runtime/httpread"`)
	w.Line(1, `"github.com/romshark/datapages/runtime/httpserve"`)
	w.Line(1, `dpsse "github.com/romshark/datapages/runtime/sse"`)
	w.Line(1, `"github.com/romshark/datapages/runtime/stream"`)
	w.Line(1, `"github.com/romshark/datapages/runtime/subject"`)
	w.Line(1, `"golang.org/x/sync/errgroup"`)
	w.Line(0, "")
	w.Byte('\t')
	// An unaliased import binds to the name the package declares.
	// Name it anyway when that differs from the last element of the path,
	// which is what a reader and the import formatter both assume it to be.
	if w.appPkgQual != appPkgName(appPkgPath) {
		w.Raw(w.appPkgQual)
		w.Byte(' ')
	}
	w.writeQuoted(appPkgPath)
	w.Byte('\n')
	if w.hasAssets() && w.genImport != "" {
		w.Byte('\t')
		w.writeQuoted(w.genImport + "/assets")
		w.Byte('\n')
	}
	if w.genImport != "" {
		w.Byte('\t')
		w.writeQuoted(w.genImport + "/href")
		w.Byte('\n')
	}
	w.Line(0, "")
	if w.prometheus {
		w.Line(1, `"github.com/prometheus/client_golang/prometheus"`)
		w.Line(1, `"github.com/romshark/datapages/runtime/prom"`)
		w.Line(1, `"github.com/prometheus/client_golang/prometheus/promhttp"`)
	}
	w.Line(1, `"github.com/starfederation/datastar-go/datastar"`)
	w.Line(0, ")")
}

func (w *Writer) hasAssets() bool { return w.assetsURLPrefix != "" }

// brokerMetricsType names what implements messaging.Metrics for the broker.
// Only a Prometheus build has counters to feed, the rest count nothing.
func (w *Writer) brokerMetricsType() string {
	if w.prometheus {
		return "brokerMetrics"
	}
	return "messaging.NoopMetrics"
}

