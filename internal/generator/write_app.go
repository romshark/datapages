func (w *Writer) writeAppInit(appPkg string) {
	w.Raw(`
// Init wires the server. It is called by datapages.NewServer,
// which is the only way to construct a Server:
//
//	s, err := datapages.NewServer[`)
	w.Raw(appPkg)
	w.Raw(`.App, `)
	if w.usage.hasSession {
		w.Raw(w.sessionDataType)
	} else {
		w.Raw(`datapages.DisableSessions`)
	}
	w.Raw(`, `)
	if w.prometheus {
		w.Raw(`datapages.EnablePrometheus`)
	} else {
		w.Raw(`datapages.DisablePrometheus`)
	}
	w.Raw(`, Server](app, broker, opts...)
//
// Supported options:
//
//   - datapages.WithLogger
//   - datapages.WithMiddleware
//   - datapages.WithHTTPServer
//   - datapages.WithDatastarJS
//   - datapages.WithAssets`)
	if w.usage.hasSession {
		w.Raw(`
//   - datapages.WithSessionManager (required)
//   - datapages.WithSessions
//   - datapages.WithCSRFProtection`)
	}
	if w.prometheus {
		w.Raw(`
//   - datapages.WithPrometheus (required)`)
	}
	w.Raw(`
func (s *Server) Init(
	cfg datapages.ServerConfig,
	app *`)
	w.Raw(appPkg)
	w.Raw(`.App,
	messageBroker messaging.Broker,
	sessionManager sessions.Manager[`)
	if w.usage.hasSession {
		w.Raw(w.sessionDataType)
	} else {
		w.Raw(`datapages.DisableSessions`)
	}
	w.Raw(`],
) error {
`)
	if !w.usage.hasSession {
		w.Raw(`	if sessionManager != nil {
		return errors.New("unexpected option WithSessionManager: package `)
		w.Raw(appPkg)
		w.Raw(` declares no session type")
	}
`)
	}
	if w.prometheus {
		w.Raw(`	if cfg.Prometheus == nil {
		// This server is generated with datapages.EnablePrometheus,
		// hence the metrics it counts must be served.
		return errors.New("missing option WithPrometheus")
	}
`)
	} else {
		w.Raw(`	if cfg.Prometheus != nil {
		// This server is generated with datapages.DisablePrometheus,
		// hence there is no instrumentation for the metrics to count.
		return errors.New("unexpected option WithPrometheus: " +
			"the server is generated with datapages.DisablePrometheus")
	}
`)
	}
	if w.usage.hasSession {
		w.Raw(`	if sessionManager == nil {
		return errors.New("missing option WithSessionManager")
	}
`)
	}
	if w.usage.stateRuntime {
		w.Raw(`	if cfg.State == nil {
		return errors.New("missing option WithStateConfig: " +
			"this app has stateful pages")
	}
`)
	}
	w.Raw(`
	assetsFS, err := httpserve.AssetsFileSystem(cfg, `)
	if w.hasAssets() {
		w.Raw(`assets.DevDir, assets.Dir`)
	} else {
		w.Raw(`"", ""`)
	}
	w.Raw(`)
	if err != nil {
		return err
	}
	cfg.AssetsFS = assetsFS

	s.Core, err = httpserve.NewCore(cfg, `)
	if w.hasAssets() {
		w.Raw(`assets.URLPrefix`)
	} else {
		w.Raw(`""`)
	}
	w.Raw(`)
	if err != nil {
		return err
	}
	s.app = app
	s.messageBroker = messageBroker
	s.messageBrokerMetrics = `)
	w.Raw(w.brokerMetricsType())
	w.Raw(`{}

	if si, ok := s.messageBroker.(messaging.StreamInitializer); ok {
		if err := si.InitStreams(MessageBrokerStreamSubjects()); err != nil {
			return fmt.Errorf("initializing message broker streams: %w", err)
		}
	}
`)
	if w.usage.stateRuntime {
		w.Raw(`	s.stateConf = cfg.State
`)
	}
	if w.usage.hasSession {
		w.Raw(`	s.Manager = auth.NewManager(s.Core, sessionManager, cfg, `)
		if w.prometheus {
			w.Raw(`prom.AuthMetrics{}`)
		} else {
			w.Raw(`nil`)
		}
		w.Raw(`)
`)
	}
	if w.usage.stream {
		w.Raw(`	s.streams = stream.NewHandler(
		s.Core, messageBroker, s.messageBrokerMetrics,
`)
		if w.usage.streamAuth {
			w.Raw(`		s.SessionManager(),
`)
		} else {
			w.Raw(`		nil,
`)
		}
		if w.prometheus {
			w.Raw(`		prom.StreamMetrics{},
`)
		} else {
			w.Raw(`		nil,
`)
		}
		w.Raw(`		s.httpErrIntern,
	)
`)
	}
	w.Raw(`
	setupHandlers(s)
`)
	w.Raw(`
	s.Build()
	href.SetLogger(s.Logger())

	return nil
}
`)
}

func (w *Writer) writeEventSubjectConsts(events []*model.Event) {
	// EvSubj* constants (subscription subjects with wildcards for prefixed events).
	w.Line(0, "")
	w.Line(0, "const (")

	// Private events first.
	for _, e := range events {
		if e.IsPrivate() {
			w.Byte('\t')
			w.Raw(evSubjConst(e))
			w.Raw(" = ")
			w.writeQuoted(evSubjValue(e))
			w.Byte('\n')
		}
	}

	w.Line(0, "")
	w.Line(1, "// Public events:")
	w.Line(0, "")

	for _, e := range events {
		if !e.IsPrivate() {
			w.Byte('\t')
			w.Raw(evSubjConst(e))
			w.Raw(" = ")
			w.writeQuoted(evSubjValue(e))
			w.Byte('\n')
		}
	}

	w.Line(0, ")")

	// EvSubjPref* constants
	// (prefix for matching events whose concrete subject is only known at runtime).
	hasPrefixed := slices.ContainsFunc(events, evUsesPrefixMatch)
	if hasPrefixed {
		w.Line(0, "")
		w.Line(0, "const (")
		for _, e := range events {
			if evUsesPrefixMatch(e) {
				w.Byte('\t')
				w.Raw(evSubjPrefConst(e))
				w.Raw(" = ")
				w.writeQuoted(evSubjPrefValue(e))
				w.Byte('\n')
			}
		}
		w.Line(0, ")")
	}
}

func (w *Writer) writeMessageBrokerStreamSubjects(events []*model.Event) {
	w.Line(0, "")
	w.Line(0, "func MessageBrokerStreamSubjects() []string {")
	w.Line(1, "return []string{")
	for _, e := range events {
		w.Raw("\t\t")
		w.Raw(evSubjConst(e))
		w.Raw(",\n")
	}
	w.Line(1, "}")
	w.Line(0, "}")
}

func (w *Writer) writeEvSubjPageFuncs(pages []*model.Page) {
	for _, p := range pages {
		if !pageHasStream(p) {
			continue
		}
		if len(p.EventHandlers) == 0 {
			w.Line(0, "")
			w.Raw("var evSubj")
			w.Raw(p.TypeName)
			w.Raw(" = []string{}\n")
			continue
		}

		// Determine which events this page handles.
		hasPublic := false
		hasPrivate := false
		hasSignalScoped := false
		hasStateIDScoped := false
		for _, eh := range p.EventHandlers {
			ev := w.eventMap[eh.EventTypeName]
			if ev == nil {
				continue
			}
			// An event can be both, which is what the call site tests for.
			// Classifying it as one leaves the builder a parameter short.
			switch {
			case ev.IsStateIDScoped():
				hasStateIDScoped = true
			case ev.IsPrivate() || ev.IsSignalScoped():
				hasPrivate = hasPrivate || ev.IsPrivate()
				hasSignalScoped = hasSignalScoped || ev.IsSignalScoped()
			default:
				hasPublic = true
			}
		}

		name := "evSubj" + p.TypeName

		signalFields := pageSignalSubjectFields(p, w.eventMap)

		// State-id-scoped events cannot mix with private/signal-scoped
		// (enforced by the parser), so a simple dedicated builder suffices.
		if hasStateIDScoped {
			w.writeEvSubjStateIDFunc(p, name, hasPublic)
			continue
		}

		if hasSignalScoped && !hasPrivate {
			// Signal-scoped events (possibly mixed with public).
			w.writeEvSubjSignalFunc(p, name, signalFields, hasPublic)
			continue
		}

		if hasPrivate && hasSignalScoped {
			// Mixed private + signal-scoped (possibly with public).
			w.writeEvSubjPrivateSignalFunc(p, name, signalFields, hasPublic)
			continue
		}

		if hasPrivate && !hasPublic {
			// All events are per-user, just take userID.
			w.Line(0, "")
			w.Raw("func ")
			w.Raw(name)
			w.Raw("(userID string) []string {\n")
			w.Line(1, "return []string{")
			for _, eh := range p.EventHandlers {
				ev := w.eventMap[eh.EventTypeName]
				if ev == nil {
					continue
				}
				w.Raw("\t\t")
				w.writeEvUserSubExpr(ev)
				w.Raw(",\n")
			}
			w.Line(1, "}")
			w.Line(0, "}")
			continue
		}

		if hasPublic && !hasPrivate {
			// All events are public, the list is the same for every stream.
			w.Line(0, "")
			w.Raw("var ")
			w.Raw(name)
			w.Raw(" = []string{\n")
			for _, eh := range p.EventHandlers {
				ev := w.eventMap[eh.EventTypeName]
				if ev == nil {
					continue
				}
				w.Byte('\t')
				w.Raw(evSubjConst(ev))
				w.Raw(",\n")
			}
			w.Line(0, "}")
			continue
		}

		// Mixed: public + private. Need conditional.
		w.Line(0, "")
		w.Raw("func ")
		w.Raw(name)
		w.Raw("(userID string) []string {\n")
		w.Line(1, "if userID == \"\" {")
		w.Line(2, "return []string{")
		for _, eh := range p.EventHandlers {
			ev := w.eventMap[eh.EventTypeName]
			if ev == nil || ev.IsPrivate() {
				continue
			}
			w.Raw("\t\t\t")
			w.Raw(evSubjConst(ev))
			w.Raw(",\n")
		}
		w.Line(2, "}")
		w.Line(1, "}")
		w.Line(1, "return []string{")

		// Public first, then private.
		for _, eh := range p.EventHandlers {
			ev := w.eventMap[eh.EventTypeName]
			if ev == nil || ev.IsPrivate() {
				continue
			}
			w.Raw("\t\t")
			w.Raw(evSubjConst(ev))
			w.Raw(",\n")
		}
		for _, eh := range p.EventHandlers {
			ev := w.eventMap[eh.EventTypeName]
			if ev == nil || !ev.IsPrivate() {
				continue
			}
			w.Raw("\t\t")
			w.writeEvUserSubExpr(ev)
			w.Raw(",\n")
		}

		w.Line(1, "}")
		w.Line(0, "}")
	}
}

// writeEvUserSubExpr emits a Go expression that builds a per-user
// subscription subject for a private event. Non-User positions
// become "*" wildcards; the User position uses the userID variable.
//
// E.g. for SubjectUser + SubjectChatRoom with subject "chat.sent":
//
//	"chat.sent." + userID + ".*"
func (w *Writer) writeEvUserSubExpr(e *model.Event) {
	var beforeUser strings.Builder
	beforeUser.WriteString(e.Subject)
	var afterUser strings.Builder
	foundUser := false
	for _, sf := range e.SubjectFields {
		if sf.Kind.IsUser() && !foundUser {
			foundUser = true
			continue
		}
		if !foundUser {
			beforeUser.WriteString(".*")
		} else {
			afterUser.WriteString(".*")
		}
	}

	w.writeQuoted(beforeUser.String() + ".")
	w.Raw(" + subject.Encode(userID)")
	if afterUser.String() != "" {
		w.Raw(" + ")
		w.writeQuoted(afterUser.String())
	}
}

// writeEvSubjSignalFunc emits an evSubjPageXxx function for pages
// whose events are signal-scoped (possibly mixed with plain public events).
// Each unique signal subject field becomes a string parameter.
func (w *Writer) writeEvSubjSignalFunc(
	p *model.Page, name string,
	signalFields []model.SubjectField, hasPublic bool,
) {
	w.Line(0, "")
	w.Raw("func ")
	w.Raw(name)
	w.Raw("(")
	idents := signalIdents(signalFields)
	identBySignal := signalIdentMap(signalFields, idents)
	for i, ident := range idents {
		if i > 0 {
			w.Raw(", ")
		}
		w.Raw("subj")
		w.Raw(ident)
		w.Raw(" string")
	}
	w.Raw(") []string {\n")
	w.Line(1, "return []string{")

	// Public events first.
	if hasPublic {
		for _, eh := range p.EventHandlers {
			ev := w.eventMap[eh.EventTypeName]
			if ev == nil || ev.IsPrivate() || ev.IsSignalScoped() {
				continue
			}
			w.Raw("\t\t")
			w.Raw(evSubjConst(ev))
			w.Raw(",\n")
		}
	}

	// Signal-scoped events.
	for _, eh := range p.EventHandlers {
		ev := w.eventMap[eh.EventTypeName]
		if ev == nil || !ev.IsSignalScoped() {
			continue
		}
		w.Raw("\t\t")
		w.writeEvSignalSubExpr(ev, identBySignal)
		w.Raw(",\n")
	}

	w.Line(1, "}")
	w.Line(0, "}")
}

// writeEvSubjStateIDFunc emits the evSubjPageXxx function for a page
// whose events are state-id-scoped (possibly mixed with plain public events).
// Takes the validated Datapages-Instance identifier and builds
// subscription subjects of the form "<base>.<stateID>".
func (w *Writer) writeEvSubjStateIDFunc(p *model.Page, name string, hasPublic bool) {
	w.Line(0, "")
	w.Raw("func ")
	w.Raw(name)
	w.Raw("(stateID string) []string {\n")
	w.Line(1, "return []string{")

	// Public events first.
	if hasPublic {
		for _, eh := range p.EventHandlers {
			ev := w.eventMap[eh.EventTypeName]
			if ev == nil || ev.IsStateIDScoped() {
				continue
			}
			w.Raw("\t\t")
			w.Raw(evSubjConst(ev))
			w.Raw(",\n")
		}
	}

	// State-id-scoped events: subject is "<base>.<stateID>", built from the
	// subject prefix constant. It must NOT be built from evSubjConst, which
	// is the wildcard subscription constant ("<base>.*") and would yield a
	// subject no publisher ever writes to.
	for _, eh := range p.EventHandlers {
		ev := w.eventMap[eh.EventTypeName]
		if ev == nil || !ev.IsStateIDScoped() {
			continue
		}
		w.Raw("\t\t")
		w.Raw(evSubjPrefConst(ev))
		w.Raw(" + stateID,\n")
	}

	w.Line(1, "}")
	w.Line(0, "}")
}

// writeEvSubjPrivateSignalFunc emits an evSubjPageXxx function for pages
// whose events mix private (user-addressed) and signal-scoped events,
// possibly with plain public events. Takes userID plus signal parameters.
func (w *Writer) writeEvSubjPrivateSignalFunc(
	p *model.Page, name string,
	signalFields []model.SubjectField, hasPublic bool,
) {
	w.Line(0, "")
	w.Raw("func ")
	w.Raw(name)
	w.Raw("(userID string")
	idents := signalIdents(signalFields)
	identBySignal := signalIdentMap(signalFields, idents)
	for _, ident := range idents {
		w.Raw(", subj")
		w.Raw(ident)
		w.Raw(" string")
	}
	w.Raw(") []string {\n")

	// A stream with no user subscribes by everything that is not addressed to one.
	// A subject built from an empty user ID names nobody: the in-memory
	// broker reads it as a literal that never matches, NATS refuses it and the
	// stream fails to open. Signal-scoped events are public and stay.
	w.Line(1, "if userID == \"\" {")
	w.Line(2, "return []string{")
	for _, eh := range p.EventHandlers {
		ev := w.eventMap[eh.EventTypeName]
		if ev == nil || ev.IsPrivate() {
			continue
		}
		w.Raw("\t\t\t")
		if ev.IsSignalScoped() {
			w.writeEvSignalSubExpr(ev, identBySignal)
		} else {
			w.Raw(evSubjConst(ev))
		}
		w.Raw(",\n")
	}
	w.Line(2, "}")
	w.Line(1, "}")

	w.Line(1, "return []string{")

	// Public events first.
	if hasPublic {
		for _, eh := range p.EventHandlers {
			ev := w.eventMap[eh.EventTypeName]
			if ev == nil || ev.IsPrivate() || ev.IsSignalScoped() {
				continue
			}
			w.Raw("\t\t")
			w.Raw(evSubjConst(ev))
			w.Raw(",\n")
		}
	}

	// Private events.
	for _, eh := range p.EventHandlers {
		ev := w.eventMap[eh.EventTypeName]
		if ev == nil || !ev.IsPrivate() {
			continue
		}
		w.Raw("\t\t")
		w.writeEvUserSubExpr(ev)
		w.Raw(",\n")
	}

	// Signal-scoped events.
	for _, eh := range p.EventHandlers {
		ev := w.eventMap[eh.EventTypeName]
		if ev == nil || !ev.IsSignalScoped() {
			continue
		}
		w.Raw("\t\t")
		w.writeEvSignalSubExpr(ev, identBySignal)
		w.Raw(",\n")
	}

	w.Line(1, "}")
	w.Line(0, "}")
}

// writeEvSignalSubExpr emits a Go expression that builds a signal-scoped
// subscription subject. Each signal-tagged subject field uses the parameter
// its signal is bound to; non-signal positions become "*" wildcards.
//
// E.g. for a field with signal:"instance_id" and subject "calc.updated":
//
//	"calc.updated." + subjInstanceID
func (w *Writer) writeEvSignalSubExpr(
	ev *model.Event, identBySignal map[string]string,
) {
	w.writeQuoted(ev.Subject + ".")
	for i, sf := range ev.SubjectFields {
		if i > 0 {
			w.Raw(` + "." + `)
		} else {
			w.Raw(" + ")
		}
		if sf.SignalName != "" {
			w.Raw("subject.Encode(subj")
			w.Raw(identBySignal[sf.SignalName])
			w.Byte(')')
		} else {
			w.writeQuoted("*")
		}
	}
}

func (w *Writer) writeBrokerSubjectKind(events []*model.Event) {
	w.Raw(`
// brokerSubjectKind folds subjects that carry a user or a tab back into the event name.
// A metric labelled with the raw subject would carry one value per user or per tab.
func brokerSubjectKind(subject string) string {
	switch {
`)
	for _, e := range events {
		if evUsesPrefixMatch(e) {
			w.Raw("\tcase strings.HasPrefix(subject, ")
			w.Raw(evSubjPrefConst(e))
			w.Raw("):\n")
		} else {
			w.Raw("\tcase subject == ")
			w.Raw(evSubjConst(e))
			w.Raw(":\n")
		}
		w.Raw("\t\treturn ")
		w.writeQuoted(e.Subject)
		w.Byte('\n')
	}
	w.Line(1, "default:")
	w.Line(2, `return "unknown"`)
	w.Line(1, "}")
	w.Line(0, "}")
}

func (w *Writer) writeSetupHandlers(m *model.App) {
	w.Line(0, "")
	w.Line(0, "func setupHandlers(s *Server) {")
	w.Line(1, "// Pages")

	for _, p := range m.Pages {
		if p.GET == nil || p.GET.OutputBody == nil {
			continue
		}

		routeForHandler := routepattern.WithTrailingSlash(p.Route)

		if p.PageSpecialization == model.PageTypeIndex {
			// Index page: GET /
			w.Line(1, "s.Mux().HandleFunc(")
			w.Line(2, "\"GET /\",")
			w.Raw("\t\ts.handle")
			w.Raw(p.TypeName)
			w.Raw("GET)\n")
		} else if routepattern.EndsInWildcard(p.Route) {
			// A {name...} wildcard runs to the end of the path already.
			// Marking the end after it puts the wildcard in the middle,
			// which is a pattern net/http will not parse.
			w.Line(1, "s.Mux().HandleFunc(")
			w.Raw("\t\t\"GET ")
			w.Raw(p.Route)
			w.Raw("\",\n")
			w.Raw("\t\ts.handle")
			w.Raw(p.TypeName)
			w.Raw("GET)\n")
		} else {
			w.Line(1, "s.Mux().HandleFunc(")
			w.Raw("\t\t\"GET ")
			w.Raw(routeForHandler)
			w.Raw("{$}\",\n")
			w.Raw("\t\ts.handle")
			w.Raw(p.TypeName)
			w.Raw("GET)\n")
		}

		// Stream endpoint.
		if pageHasStream(p) {
			streamPath := routeStreamPath(p.Route)

			w.Line(1, "s.Mux().HandleFunc(")
			w.Raw("\t\t\"GET ")
			w.Raw(streamPath)
			w.Raw("{$}\",\n")
			w.Raw("\t\ts.handle")
			w.Raw(p.TypeName)
			w.Raw("GETStream)\n")

			if pageHasAnonStream(p, w.eventMap) {
				w.Line(1, "s.Mux().HandleFunc(")
				w.Raw("\t\t\"GET ")
				w.Raw(streamPath)
				w.Raw("anon/{$}\",\n")
				w.Raw("\t\ts.handle")
				w.Raw(p.TypeName)
				w.Raw("GETStreamAnon)\n")
			}
		}
	}

	// App-level actions.
	for _, h := range m.Actions {
		route := routepattern.WithTrailingSlash(h.Route)
		method := strings.ToUpper(h.HTTPMethod)

		w.Line(1, "s.Mux().HandleFunc(")
		w.Raw("\t\t\"")
		w.Raw(method)
		w.Byte(' ')
		w.Raw(route)
		w.Raw("{$}\",\n")
		w.Raw("\t\ts.handle")
		w.Raw(method)
		w.Raw(h.Name)
		w.Raw(")\n")
	}

	// Page actions.
	for _, p := range m.Pages {
		for _, h := range p.Actions {
			route := routepattern.WithTrailingSlash(h.Route)
			method := strings.ToUpper(h.HTTPMethod)

			w.Line(1, "s.Mux().HandleFunc(")
			w.Raw("\t\t\"")
			w.Raw(method)
			w.Byte(' ')
			w.Raw(route)
			w.Raw("{$}\",\n")
			w.Raw("\t\ts.handle")
			w.Raw(p.TypeName)
			w.Raw(method)
			w.Raw(h.Name)
			w.Raw(")\n")
		}
	}

	w.Line(0, "}")
}

func (w *Writer) writeHTTPErrFallback() {
	if !w.usage.errSentinels {
		w.Raw(`	const code = http.StatusInternalServerError
	http.Error(w, http.StatusText(code), code)
`)
		return
	}
	w.Raw(`	httpserve.WriteErrStatus(w, err)
`)
}

// needsCSRFOnly reports whether a handler has to run the session check for the
// CSRF token alone, because it reads nothing of the session itself.
//
// The check lives inside the session helper. A state-changing action that
// declares neither session nor sessionToken would never call it,
// and a cross-site page can make a browser send exactly that request.
func needsCSRFOnly(h *model.Handler, m *model.App) bool {
	if m.Session == nil {
		return false
	}
	switch strings.ToUpper(h.HTTPMethod) {
	case "GET", "HEAD", "OPTIONS":
		// Nothing to protect: these change nothing.
		return false
	}
	return true
}

// writeCSRFOnlyCheck emits the session lookup a handler runs for its CSRF token.
// The session itself is not passed on; the handler did not ask for it.
func (w *Writer) writeCSRFOnlyCheck() {
	w.Line(1, "// CSRF protection covers every state-changing action, including")
	w.Line(1, "// the ones that read nothing of the session.")
	w.Line(1, "if _, _, ok := s.ReadSession(w, r); !ok {")
	w.Line(2, "return")
	w.Line(1, "}")
}

// writeAppErrHelpers emits httpErrIntern,
// which answers a request whose handler failed.
//
// PageError500 and RecoverError are separate features and each one applies on its own.
// A page load is answered by the 500 page when the app supplies one.
// A Datastar request is answered by RecoverError when the app defines it,
// because that request expects an event stream rather than a document.
// An app that has only one of the two gets it for the requests it covers,
// and the plain HTTP error for the rest.
func (w *Writer) writeAppErrHelpers(m *model.App, appPkg string) {
	hasPage := m.PageError500 != nil
	hasRecover := m.RecoverError != nil

	if !hasPage && !hasRecover {
		w.Raw(`
func (s *Server) httpErrIntern(
	w http.ResponseWriter, _ *http.Request,
	_ *datastar.ServerSentEventGenerator, msg string, err error,
) {
	s.LogErr(msg, err)
`)
		w.writeHTTPErrFallback()
		w.Raw(`}
`)
		return
	}

	if hasPage {
		// httpErrIntern answers a page load by rendering PageError500.
		// The handler of that page therefore can't report through it.
		w.Raw(`
// httpErrFinal writes the error response without rendering PageError500.
// The PageError500 handler uses it so it can't render itself.
func (s *Server) httpErrFinal(w http.ResponseWriter, msg string, err error) {
	s.LogErr(msg, err)
`)
		w.writeHTTPErrFallback()
		w.Raw(`}
`)
	}

	w.Raw(`
func (s *Server) httpErrIntern(
	w http.ResponseWriter, r *http.Request,
	sse *datastar.ServerSentEventGenerator, msg string, err error,
) {
	s.LogErr(msg, err)
`)
	if hasPage {
		w.Raw(`	if !httpserve.IsDatastarRequest(r) {
		// A page load gets the app's own 500 page, with the status that
		// says what happened. The page's own route serves 200;
		// this is the other way in.
		w.WriteHeader(http.StatusInternalServerError)
		s.handlePageError500GET(w, r)
		return
	}
`)
	}
	if hasRecover {
		w.Raw(`	// The response of a Datastar request is an event stream. Once one is
	// open the status line is gone, which is what committed reports.
	committed := sse != nil
	if sse == nil {
		sse = datastar.NewSSE(w, r, datastar.WithCompression())
		committed = true
	}
	errRecover := s.`)
		w.Raw(appPkg)
		w.Raw(`.RecoverError(`)
		for i, kind := range m.RecoverError.OrderedInputs {
			if i > 0 {
				w.Raw(", ")
			}
			if kind == model.InputKindSSE {
				w.Raw("dpsse.New(sse)")
			} else {
				w.Raw("err")
			}
		}
		w.Raw(`)
	if errRecover == nil {
`)
		if w.prometheus {
			w.Raw(`		prom.InternalErrorRecovered()
`)
		}
		w.Raw(`		return // Feedback delivered gracefully.
	}
	// RecoverError failed — fall back to HTTP error response.
`)
		if w.prometheus {
			w.Raw(`	prom.InternalErrorNotRecovered()
`)
		}
		w.Raw(`	s.Logger().Error("recovering error",
		slog.Any("orig.msg", msg),
		slog.Any("orig.err", err),
		slog.Any("err", errRecover))
	if committed {
		// http.Error would write a status the client already received,
		// and append its text to the event stream the client is reading.
		return
	}
`)
	}
	w.writeHTTPErrFallback()
	w.Raw(`}
`)
}

func (w *Writer) writeRender404(m *model.App, appPkg string) {
	p := m.PageError404

	w.Line(0, "")
	w.Line(0, "func (s *Server) render404(w http.ResponseWriter, r *http.Request) {")
	w.Line(1, "// The URL is claimed by no page. Whatever the app renders for it,")
	w.Line(1, "// the response says so: a cache that stores it and a crawler that")
	w.Line(1, "// reads it both go by the status.")
	w.Line(1, "w.WriteHeader(http.StatusNotFound)")

	h404 := p.GET.Handler
	headNeedsSess := m.GlobalHeadGenerator != nil && m.GlobalHeadGenerator.InputSession
	if h404.InputSession != nil || headNeedsSess {
		w.Line(1, "sess, _, ok := s.ReadSession(w, r)")
		w.Line(1, "if !ok {")
		w.Line(2, "return")
		w.Line(1, "}")
		w.Line(0, "")
	}

	w.writePageConstructorStmt("p", p, appPkg)
	w.Line(0, "")

	// Call GET.
	w.writeGETCall(p, m, appPkg, "render404")

	w.Line(0, "}")
}

