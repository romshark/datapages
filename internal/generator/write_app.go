func (w *Writer) writeEvSubjPageFuncs(pages []*model.Page) {
	for _, p := range pages {
		if !pageHasStream(p) {
			continue
		}
		if len(p.EventHandlers) == 0 {
			w.Line(0, "")
			w.Raw("var evSubj")
			w.Raw(p.TypeName)
			w.Raw(" = []string{}\n")
			continue
		}

		// Determine which events this page handles.
		hasPublic := false
		hasPrivate := false
		hasSignalScoped := false
		hasStateIDScoped := false
		for _, eh := range p.EventHandlers {
			ev := w.eventMap[eh.EventTypeName]
			if ev == nil {
				continue
			}
			// An event can be both, which is what the call site tests for.
			// Classifying it as one leaves the builder a parameter short.
			switch {
			case ev.IsStateIDScoped():
				hasStateIDScoped = true
			case ev.IsPrivate() || ev.IsSignalScoped():
				hasPrivate = hasPrivate || ev.IsPrivate()
				hasSignalScoped = hasSignalScoped || ev.IsSignalScoped()
			default:
				hasPublic = true
			}
		}

		name := "evSubj" + p.TypeName

		signalFields := pageSignalSubjectFields(p, w.eventMap)

		// State-id-scoped events cannot mix with private/signal-scoped
		// (enforced by the parser), so a simple dedicated builder suffices.
		if hasStateIDScoped {
			w.writeEvSubjStateIDFunc(p, name, hasPublic)
			continue
		}

		if hasSignalScoped && !hasPrivate {
			// Signal-scoped events (possibly mixed with public).
			w.writeEvSubjSignalFunc(p, name, signalFields, hasPublic)
			continue
		}

		if hasPrivate && hasSignalScoped {
			// Mixed private + signal-scoped (possibly with public).
			w.writeEvSubjPrivateSignalFunc(p, name, signalFields, hasPublic)
			continue
		}

		if hasPrivate && !hasPublic {
			// All events are per-user, just take userID.
			w.Line(0, "")
			w.Raw("func ")
			w.Raw(name)
			w.Raw("(userID string) []string {\n")
			w.Line(1, "return []string{")
			for _, eh := range p.EventHandlers {
				ev := w.eventMap[eh.EventTypeName]
				if ev == nil {
					continue
				}
				w.Raw("\t\t")
				w.writeEvUserSubExpr(ev)
				w.Raw(",\n")
			}
			w.Line(1, "}")
			w.Line(0, "}")
			continue
		}

		if hasPublic && !hasPrivate {
			// All events are public, the list is the same for every stream.
			w.Line(0, "")
			w.Raw("var ")
			w.Raw(name)
			w.Raw(" = []string{\n")
			for _, eh := range p.EventHandlers {
				ev := w.eventMap[eh.EventTypeName]
				if ev == nil {
					continue
				}
				w.Byte('\t')
				w.Raw(evSubjConst(ev))
				w.Raw(",\n")
			}
			w.Line(0, "}")
			continue
		}

		// Mixed: public + private. Need conditional.
		w.Line(0, "")
		w.Raw("func ")
		w.Raw(name)
		w.Raw("(userID string) []string {\n")
		w.Line(1, "if userID == \"\" {")
		w.Line(2, "return []string{")
		for _, eh := range p.EventHandlers {
			ev := w.eventMap[eh.EventTypeName]
			if ev == nil || ev.IsPrivate() {
				continue
			}
			w.Raw("\t\t\t")
			w.Raw(evSubjConst(ev))
			w.Raw(",\n")
		}
		w.Line(2, "}")
		w.Line(1, "}")
		w.Line(1, "return []string{")

		// Public first, then private.
		for _, eh := range p.EventHandlers {
			ev := w.eventMap[eh.EventTypeName]
			if ev == nil || ev.IsPrivate() {
				continue
			}
			w.Raw("\t\t")
			w.Raw(evSubjConst(ev))
			w.Raw(",\n")
		}
		for _, eh := range p.EventHandlers {
			ev := w.eventMap[eh.EventTypeName]
			if ev == nil || !ev.IsPrivate() {
				continue
			}
			w.Raw("\t\t")
			w.writeEvUserSubExpr(ev)
			w.Raw(",\n")
		}

		w.Line(1, "}")
		w.Line(0, "}")
	}
}

// writeEvUserSubExpr emits a Go expression that builds a per-user
// subscription subject for a private event. Non-User positions
// become "*" wildcards; the User position uses the userID variable.
//
// E.g. for SubjectUser + SubjectChatRoom with subject "chat.sent":
//
//	"chat.sent." + userID + ".*"
func (w *Writer) writeEvUserSubExpr(e *model.Event) {
	var beforeUser strings.Builder
	beforeUser.WriteString(e.Subject)
	var afterUser strings.Builder
	foundUser := false
	for _, sf := range e.SubjectFields {
		if sf.Kind.IsUser() && !foundUser {
			foundUser = true
			continue
		}
		if !foundUser {
			beforeUser.WriteString(".*")
		} else {
			afterUser.WriteString(".*")
		}
	}

	w.writeQuoted(beforeUser.String() + ".")
	w.Raw(" + userID")
	if afterUser.String() != "" {
		w.Raw(" + ")
		w.writeQuoted(afterUser.String())
	}
}

// writeEvSubjSignalFunc emits an evSubjPageXxx function for pages
// whose events are signal-scoped (possibly mixed with plain public events).
// Each unique signal subject field becomes a string parameter.
func (w *Writer) writeEvSubjSignalFunc(
	p *model.Page, name string,
	signalFields []model.SubjectField, hasPublic bool,
) {
	w.Line(0, "")
	w.Raw("func ")
	w.Raw(name)
	w.Raw("(")
	idents := signalIdents(signalFields)
	identBySignal := signalIdentMap(signalFields, idents)
	for i, ident := range idents {
		if i > 0 {
			w.Raw(", ")
		}
		w.Raw("subj")
		w.Raw(ident)
		w.Raw(" string")
	}
	w.Raw(") []string {\n")
	w.Line(1, "return []string{")

	// Public events first.
	if hasPublic {
		for _, eh := range p.EventHandlers {
			ev := w.eventMap[eh.EventTypeName]
			if ev == nil || ev.IsPrivate() || ev.IsSignalScoped() {
				continue
			}
			w.Raw("\t\t")
			w.Raw(evSubjConst(ev))
			w.Raw(",\n")
		}
	}

	// Signal-scoped events.
	for _, eh := range p.EventHandlers {
		ev := w.eventMap[eh.EventTypeName]
		if ev == nil || !ev.IsSignalScoped() {
			continue
		}
		w.Raw("\t\t")
		w.writeEvSignalSubExpr(ev, identBySignal)
		w.Raw(",\n")
	}

	w.Line(1, "}")
	w.Line(0, "}")
}

// writeEvSubjStateIDFunc emits the evSubjPageXxx function for a page
// whose events are state-id-scoped (possibly mixed with plain public events).
// Takes the validated Datapages-Instance identifier and builds
// subscription subjects of the form "<base>.<stateID>".
func (w *Writer) writeEvSubjStateIDFunc(p *model.Page, name string, hasPublic bool) {
	w.Line(0, "")
	w.Raw("func ")
	w.Raw(name)
	w.Raw("(stateID string) []string {\n")
	w.Line(1, "return []string{")

	// Public events first.
	if hasPublic {
		for _, eh := range p.EventHandlers {
			ev := w.eventMap[eh.EventTypeName]
			if ev == nil || ev.IsStateIDScoped() {
				continue
			}
			w.Raw("\t\t")
			w.Raw(evSubjConst(ev))
			w.Raw(",\n")
		}
	}

	// State-id-scoped events: subject is "<base>.<stateID>", built from the
	// subject prefix constant. It must NOT be built from evSubjConst, which
	// is the wildcard subscription constant ("<base>.*") and would yield a
	// subject no publisher ever writes to.
	for _, eh := range p.EventHandlers {
		ev := w.eventMap[eh.EventTypeName]
		if ev == nil || !ev.IsStateIDScoped() {
			continue
		}
		w.Raw("\t\t")
		w.Raw(evSubjPrefConst(ev))
		w.Raw(" + stateID,\n")
	}

	w.Line(1, "}")
	w.Line(0, "}")
}

// writeEvSubjPrivateSignalFunc emits an evSubjPageXxx function for pages
// whose events mix private (user-addressed) and signal-scoped events,
// possibly with plain public events. Takes userID plus signal parameters.
func (w *Writer) writeEvSubjPrivateSignalFunc(
	p *model.Page, name string,
	signalFields []model.SubjectField, hasPublic bool,
) {
	w.Line(0, "")
	w.Raw("func ")
	w.Raw(name)
	w.Raw("(userID string")
	idents := signalIdents(signalFields)
	identBySignal := signalIdentMap(signalFields, idents)
	for _, ident := range idents {
		w.Raw(", subj")
		w.Raw(ident)
		w.Raw(" string")
	}
	w.Raw(") []string {\n")

	// A stream with no user subscribes by everything that is not addressed to one.
	// A subject built from an empty user ID names nobody: the in-memory
	// broker reads it as a literal that never matches, NATS refuses it and the
	// stream fails to open. Signal-scoped events are public and stay.
	w.Line(1, "if userID == \"\" {")
	w.Line(2, "return []string{")
	for _, eh := range p.EventHandlers {
		ev := w.eventMap[eh.EventTypeName]
		if ev == nil || ev.IsPrivate() {
			continue
		}
		w.Raw("\t\t\t")
		if ev.IsSignalScoped() {
			w.writeEvSignalSubExpr(ev, identBySignal)
		} else {
			w.Raw(evSubjConst(ev))
		}
		w.Raw(",\n")
	}
	w.Line(2, "}")
	w.Line(1, "}")

	w.Line(1, "return []string{")

	// Public events first.
	if hasPublic {
		for _, eh := range p.EventHandlers {
			ev := w.eventMap[eh.EventTypeName]
			if ev == nil || ev.IsPrivate() || ev.IsSignalScoped() {
				continue
			}
			w.Raw("\t\t")
			w.Raw(evSubjConst(ev))
			w.Raw(",\n")
		}
	}

	// Private events.
	for _, eh := range p.EventHandlers {
		ev := w.eventMap[eh.EventTypeName]
		if ev == nil || !ev.IsPrivate() {
			continue
		}
		w.Raw("\t\t")
		w.writeEvUserSubExpr(ev)
		w.Raw(",\n")
	}

	// Signal-scoped events.
	for _, eh := range p.EventHandlers {
		ev := w.eventMap[eh.EventTypeName]
		if ev == nil || !ev.IsSignalScoped() {
			continue
		}
		w.Raw("\t\t")
		w.writeEvSignalSubExpr(ev, identBySignal)
		w.Raw(",\n")
	}

	w.Line(1, "}")
	w.Line(0, "}")
}

// writeEvSignalSubExpr emits a Go expression that builds a signal-scoped
// subscription subject. Each signal-tagged subject field uses the parameter
// its signal is bound to; non-signal positions become "*" wildcards.
//
// E.g. for a field with signal:"instance_id" and subject "calc.updated":
//
//	"calc.updated." + subjInstanceID
func (w *Writer) writeEvSignalSubExpr(
	ev *model.Event, identBySignal map[string]string,
) {
	w.writeQuoted(ev.Subject + ".")
	for i, sf := range ev.SubjectFields {
		if i > 0 {
			w.Raw(` + "." + `)
		} else {
			w.Raw(" + ")
		}
		if sf.SignalName != "" {
			w.Raw("subj")
			w.Raw(identBySignal[sf.SignalName])
		} else {
			w.writeQuoted("*")
		}
	}
}

