// Package serverscan finds the datapages.NewServer calls of a module and reads
// the app package, the session data type, the metrics mode and the destination
// package out of their type arguments.
//
// It works on the AST alone. A type argument list needs no type information,
// which is what lets the scan read a main.go naming a generated package that
// the first run has not written yet.
package serverscan

import (
	"fmt"
	"go/ast"
	"go/parser"
	"go/printer"
	"go/token"
	"io/fs"
	"os"
	"path/filepath"
	"slices"
	"strconv"
	"strings"
)

// DatapagesImport is the import path of the datapages package.
const DatapagesImport = "github.com/romshark/datapages"

// GeneratedHeader is the comment every generated file starts with.
// It is what marks a package as one datapages wrote.
const GeneratedHeader = "// Code generated by " + DatapagesImport + "; DO NOT EDIT."

// DefaultAppDir is the app package the scan falls back to
// when the module holds no NewServer call yet.
const DefaultAppDir = "app"

// GenSubdir is the package an app package is generated into.
// It always sits directly under the app package, which is what lets one
// module build any number of applications.
const GenSubdir = "datapagesgen"

// ServerTypeName is the name of the generated server type.
const ServerTypeName = "Server"

// DisableSessions is the name of the type that means "no sessions".
const DisableSessions = "DisableSessions"

// EnablePrometheus and DisablePrometheus are the names of the datapages types
// the Metrics type argument is written with.
const (
	EnablePrometheus  = "EnablePrometheus"
	DisablePrometheus = "DisablePrometheus"
)

// TypeArg is one type argument of a NewServer call.
type TypeArg struct {
	// Src is the argument as written, for example "app.App".
	Src string

	// Import is the import path the qualifier resolves to.
	// Empty when the type is declared in the calling package.
	Import string

	// Name is the type name, for example "App".
	Name string
}

// same reports whether a and b name the same type.
//
// Comparing what is written would make an import alias a type of its own,
// and a file importing two packages of the same name has to alias one of them.
// A type declared in the calling package resolves to no import and is compared
// as written: there is no import path to compare it by.
func (a TypeArg) same(b TypeArg) bool {
	if a.Import == "" || b.Import == "" {
		return a.Src == b.Src
	}
	return a.Import == b.Import && a.Name == b.Name
}

// Call is one datapages.NewServer call.
type Call struct {
	// Pos is where the call is written.
	Pos token.Position

	// Dir is the package the call is written in,
	// relative to the module root.
	Dir string

	// Main reports whether that package is a command.
	// It is what the dev server builds and runs.
	Main bool

	// App is the App type argument, the application type.
	App TypeArg

	// SessionData is the SessionData type argument.
	SessionData TypeArg

	// Metrics is the Metrics type argument, datapages.EnablePrometheus or
	// datapages.DisablePrometheus.
	Metrics TypeArg

	// Server is the S type argument, the generated server type.
	Server TypeArg

	// HasSession is false when SessionData is datapages.DisableSessions.
	HasSession bool

	// Prometheus is true when Metrics is datapages.EnablePrometheus.
	Prometheus bool
}

// App is one app package of the module, with the calls that build a server
// for it and the package they generate into.
type App struct {
	// Name is the last element of Dir, which is what names the app on the
	// command line, for example "frontend".
	Name string

	// Dir is the app package relative to the module root,
	// for example "app" or "app/frontend".
	Dir string

	// Import is the import path of the app package.
	Import string

	// GenDir and GenImport are the package generated for it, which always
	// sits directly under the app package.
	GenDir    string
	GenImport string

	// Calls holds the NewServer calls naming this app, in the order read.
	Calls []Call

	// SessionData is the SessionData type argument the calls agree on.
	SessionData TypeArg

	// Metrics is the Metrics type argument the calls agree on.
	Metrics TypeArg

	// HasSession is false when SessionData is datapages.DisableSessions.
	HasSession bool

	// Prometheus reports that the calls name datapages.EnablePrometheus,
	// which is what the metrics instrumentation is generated for.
	Prometheus bool
}

// Result is what a module was found to contain.
type Result struct {
	// Apps holds one entry per app package, ordered by directory.
	Apps []App

	// Fallback reports that the module holds no NewServer call and Apps holds
	// the default alone. The caller writes a main.go in that case.
	Fallback bool
}

// Scan reads the NewServer calls of the module rooted at moduleDir, whose
// module path is modulePath, and reports what to generate and where.
//
// One module may build any number of applications. Calls are grouped by the
// app package their App type argument names, and each group generates into
// the datapagesgen package of that app.
//
// A module without a single call is not an error: Apps holds the default app
// package alone and Fallback is true.
func Scan(moduleDir, modulePath string) (Result, error) {
	var errs Errors
	calls := scanDir(moduleDir, moduleDir, &errs)
	if errs.Len() > 0 {
		return Result{}, errs.Err()
	}
	if len(calls) == 0 {
		return Result{
			Apps:     []App{defaultApp(modulePath)},
			Fallback: true,
		}, nil
	}

	byImport := map[string]*App{}
	var order []string
	for _, c := range calls {
		dir, err := dirOf(c.App, modulePath)
		if err != nil {
			errs.addf(c.Pos, "%s", err)
			continue
		}
		a := byImport[c.App.Import]
		if a == nil {
			a = &App{
				Name:        filepath.Base(dir),
				Dir:         dir,
				Import:      c.App.Import,
				GenDir:      filepath.Join(dir, GenSubdir),
				GenImport:   c.App.Import + "/" + GenSubdir,
				SessionData: c.SessionData,
				HasSession:  c.HasSession,
				Metrics:     c.Metrics,
				Prometheus:  c.Prometheus,
			}
			byImport[c.App.Import] = a
			order = append(order, c.App.Import)
		}
		checkDestinationArg(a, c, &errs)
		checkAgreement(moduleDir, a, c, &errs)
		a.Calls = append(a.Calls, c)
	}
	if errs.Len() > 0 {
		return Result{}, errs.Err()
	}

	slices.Sort(order)
	res := Result{Apps: make([]App, 0, len(order))}
	for _, imp := range order {
		a := byImport[imp]
		checkDestination(moduleDir, *a, &errs)
		res.Apps = append(res.Apps, *a)
	}
	if errs.Len() > 0 {
		return Result{}, errs.Err()
	}
	return res, nil
}

// Find returns the app named on the command line, matched against its name or
// its directory. ok is false when nothing matches.
func (r Result) Find(name string) (App, bool) {
	name = filepath.ToSlash(name)
	for _, a := range r.Apps {
		if a.Name == name || filepath.ToSlash(a.Dir) == name {
			return a, true
		}
	}
	return App{}, false
}

// Names lists the app names, which is what an ambiguous command line is
// answered with.
func (r Result) Names() []string {
	names := make([]string, len(r.Apps))
	for i, a := range r.Apps {
		names[i] = a.Name
	}
	return names
}

// Cmd returns the command package that builds this app, relative to the module
// root. ok is false when no call to it is written in one, which is what a
// module whose only calls are in tests looks like.
func (a App) Cmd() (dir string, ok bool) {
	for _, c := range a.Calls {
		if c.Main {
			return c.Dir, true
		}
	}
	return "", false
}

// defaultApp is what a module with no NewServer call is generated as.
func defaultApp(modulePath string) App {
	return App{
		Name:      DefaultAppDir,
		Dir:       DefaultAppDir,
		Import:    modulePath + "/" + DefaultAppDir,
		GenDir:    filepath.Join(DefaultAppDir, GenSubdir),
		GenImport: modulePath + "/" + DefaultAppDir + "/" + GenSubdir,
	}
}

// checkDestinationArg holds the S type argument to the one package the app
// generates into. Where generated code goes is not a choice: it follows the app
// package, which is what lets one module build any number of applications.
func checkDestinationArg(a *App, c Call, errs *Errors) {
	if c.Server.Import == a.GenImport && c.Server.Name == ServerTypeName {
		return
	}
	errs.addf(c.Pos,
		"datapages.NewServer generates into %s, but %s generates into %s",
		c.Server.Src, a.Dir, a.GenDir)
	errs.hint("fix: name " + a.GenImport + "." + ServerTypeName)
}

// checkAgreement holds every call naming one app to the same session data type
// and the same metrics mode. Two calls disagreeing would mean two servers
// generated from one model.
func checkAgreement(moduleDir string, a *App, c Call, errs *Errors) {
	if len(a.Calls) == 0 {
		return
	}
	first := relTo(moduleDir, a.Calls[0].Pos)
	if !c.SessionData.same(a.SessionData) {
		errs.addf(c.Pos,
			"datapages.NewServer names SessionData %s for %s, "+
				"but the call at %s names %s",
			c.SessionData.Src, a.Dir, first, a.SessionData.Src)
		errs.hint("every call naming one app package must name one session type")
	}
	if !c.Metrics.same(a.Metrics) {
		errs.addf(c.Pos,
			"datapages.NewServer names Metrics %s for %s, "+
				"but the call at %s names %s",
			c.Metrics.Src, a.Dir, first, a.Metrics.Src)
		errs.hint("every call naming one app package must name one metrics mode")
	}
}

// CheckSessionData reports a call whose SessionData type argument disagrees
// with the app package. hasSession is what the app package was parsed to
// declare, which is what the check is against.
//
// It runs after the app package was parsed, hence it is not part of [Scan].
//
// Whether the built server carries a session manager is not checked here: the
// options may be assembled in a package the AST scan never reads. The generated
// Init rejects a missing or unexpected datapages.WithSessionManager,
// where the assembled options are visible.
func CheckSessionData(a App, hasSession bool) error {
	var errs Errors
	for _, c := range a.Calls {
		switch {
		case !c.HasSession && hasSession:
			errs.addf(c.Pos,
				"datapages.NewServer with SessionData datapages.%s, "+
					"but %s declares a session type", DisableSessions, a.Dir)
		case c.HasSession && !hasSession:
			errs.addf(c.Pos,
				"datapages.NewServer with SessionData %s, "+
					"but %s declares no session type", c.SessionData.Src, a.Dir)
			errs.hint("fix: use datapages." + DisableSessions)
		}
	}
	return errs.Err()
}

// checkDestination refuses a destination that datapages did not write.
// A package that does not exist yet passes, the first run is what creates it.
func checkDestination(moduleDir string, a App, errs *Errors) {
	genDir := a.GenDir
	dir := filepath.Join(moduleDir, genDir)
	entries, err := os.ReadDir(dir)
	if err != nil {
		return // Not there yet, the first run creates it.
	}
	fset := token.NewFileSet()
	sawGo, declared := false, ""
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".go") {
			continue
		}
		sawGo = true
		p := filepath.Join(dir, e.Name())
		f, err := parser.ParseFile(fset, p, nil, parser.ParseComments)
		if err != nil {
			continue
		}
		generated := isGenerated(f)
		if declaresType(f, ServerTypeName) {
			if generated {
				return // The type is there and datapages wrote it.
			}
			declared = filepath.Join(genDir, e.Name())
			break
		}
		if generated {
			return // A generated package that has not got the type yet.
		}
	}
	if !sawGo {
		return // An empty directory is not a package.
	}
	errs.addf(a.Calls[0].Pos,
		"datapages.NewServer generates into %s, which datapages did not generate",
		a.Calls[0].Server.Src)
	if declared != "" {
		errs.addf(token.Position{Filename: declared},
			"%s declared here", ServerTypeName)
	}
	errs.hint("name a package datapages generates into, or delete " +
		filepath.Join(genDir) + " to have it generated")
}

// dirOf resolves the app package a type argument names to a directory
// relative to the module root.
func dirOf(a TypeArg, modulePath string) (string, error) {
	switch {
	case a.Import == "":
		return "", fmt.Errorf("the app type %s must live in its own package", a.Src)
	case a.Import == modulePath:
		return "", fmt.Errorf(
			"the app type %s must not live in the module root", a.Src,
		)
	case !strings.HasPrefix(a.Import, modulePath+"/"):
		return "", fmt.Errorf("the app type %s lives in another module (%s)",
			a.Src, a.Import)
	case strings.HasSuffix(a.Import, "/"+GenSubdir):
		return "", fmt.Errorf(
			"the app type %s lives in a generated package", a.Src,
		)
	}
	return filepath.FromSlash(strings.TrimPrefix(a.Import, modulePath+"/")), nil
}

// scanDir reads every package under dir, skipping nested modules,
// and returns the NewServer calls it found.
func scanDir(root, dir string, errs *Errors) []Call {
	var calls []Call
	_ = filepath.WalkDir(dir, func(p string, d fs.DirEntry, err error) error {
		if err != nil || !d.IsDir() {
			return nil //nolint:nilerr // An unreadable directory holds no calls.
		}
		if p != dir && skipDir(p, d.Name()) {
			return filepath.SkipDir
		}
		calls = append(calls, scanPackage(root, p, errs)...)
		return nil
	})
	return calls
}

// skipDir reports whether a directory holds no code of this module.
func skipDir(path, name string) bool {
	if strings.HasPrefix(name, ".") || strings.HasPrefix(name, "_") ||
		name == "vendor" || name == "node_modules" || name == "testdata" {
		return true
	}
	// A directory with its own go.mod is another module.
	_, err := os.Stat(filepath.Join(path, "go.mod"))
	return err == nil
}

// scanPackage reads the Go files of one directory, without recursing.
func scanPackage(root, dir string, errs *Errors) []Call {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil
	}
	fset := token.NewFileSet()
	var files []*ast.File
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".go") {
			continue
		}
		f, err := parser.ParseFile(fset, filepath.Join(dir, e.Name()), nil, 0)
		if err != nil {
			// A file that does not parse holds no call worth reading.
			// The compiler reports it, the scan stays quiet.
			continue
		}
		files = append(files, f)
	}
	relDir := dir
	if rel, err := filepath.Rel(root, dir); err == nil {
		relDir = rel
	}
	var calls []Call
	for _, f := range files {
		dp, dot := importName(f, DatapagesImport)
		if dot != nil {
			pos := relTo(root, fset.Position(dot.Pos()))
			errs.addf(pos, "the datapages package must not be dot-imported")
			errs.hint("fix: import " + DatapagesImport +
				" under a name, the scan reads the calls by their qualifier")
			continue
		}
		if dp == "" {
			continue
		}
		found := scanFile(fset, f, dp, errs)
		for i := range found {
			found[i].Dir = relDir
			found[i].Main = f.Name.Name == "main"
		}
		calls = append(calls, found...)
	}
	for i := range calls {
		calls[i].Pos.Filename = relTo(root, calls[i].Pos).Filename
	}
	return calls
}

// scanFile reads the NewServer calls of one file.
func scanFile(
	fset *token.FileSet, f *ast.File, dp string, errs *Errors,
) []Call {
	var calls []Call
	ast.Inspect(f, func(n ast.Node) bool {
		call, ok := n.(*ast.CallExpr)
		if !ok {
			return true
		}
		targs, ok := typeArgsOf(call.Fun, dp, "NewServer")
		if !ok {
			return true
		}
		pos := fset.Position(call.Lparen)
		if len(targs) != 4 {
			errs.addf(pos,
				"datapages.NewServer needs four type arguments, got %d",
				len(targs))
			errs.hint("fix: datapages.NewServer[app.App, " +
				"datapages." + DisableSessions + ", " +
				"datapages." + DisablePrometheus + ", datapagesgen.Server]")
			return true
		}
		c := Call{
			Pos:         pos,
			App:         typeArg(f, targs[0]),
			SessionData: typeArg(f, targs[1]),
			Metrics:     typeArg(f, targs[2]),
			Server:      typeArg(f, targs[3]),
		}
		c.HasSession = c.SessionData.Import != DatapagesImport ||
			c.SessionData.Name != DisableSessions
		if !checkMetricsArg(c.Metrics, pos, errs) {
			return true
		}
		c.Prometheus = c.Metrics.Name == EnablePrometheus
		calls = append(calls, c)
		return true
	})
	return calls
}

// checkMetricsArg holds the Metrics type argument to datapages.EnablePrometheus and
// datapages.DisablePrometheus. The compiler rejects anything else,
// the scan runs before it and says so first.
func checkMetricsArg(m TypeArg, pos token.Position, errs *Errors) bool {
	if m.Import == DatapagesImport &&
		(m.Name == EnablePrometheus || m.Name == DisablePrometheus) {
		return true
	}
	errs.addf(pos,
		"datapages.NewServer names Metrics %s, "+
			"which is neither datapages.%s nor datapages.%s",
		m.Src, EnablePrometheus, DisablePrometheus)
	errs.hint("fix: use datapages." + DisablePrometheus + " to generate no metrics")
	return false
}

// typeArgsOf returns the type arguments of a call of pkg.name.
func typeArgsOf(fun ast.Expr, pkg, name string) ([]ast.Expr, bool) {
	var x ast.Expr
	var targs []ast.Expr
	switch e := fun.(type) {
	case *ast.IndexExpr:
		x, targs = e.X, []ast.Expr{e.Index}
	case *ast.IndexListExpr:
		x, targs = e.X, e.Indices
	default:
		return nil, false
	}
	sel, ok := x.(*ast.SelectorExpr)
	if !ok || sel.Sel.Name != name {
		return nil, false
	}
	id, ok := sel.X.(*ast.Ident)
	if !ok || id.Name != pkg {
		return nil, false
	}
	return targs, true
}

// typeArg renders one type argument and resolves its qualifier to an import path.
func typeArg(f *ast.File, e ast.Expr) TypeArg {
	switch t := e.(type) {
	case *ast.Ident:
		return TypeArg{Src: t.Name, Name: t.Name}
	case *ast.SelectorExpr:
		if id, ok := t.X.(*ast.Ident); ok {
			return TypeArg{
				Src:    id.Name + "." + t.Sel.Name,
				Import: importPath(f, id.Name),
				Name:   t.Sel.Name,
			}
		}
	}
	return TypeArg{Src: exprString(e)}
}

// importName returns the name path is bound to in f, empty when f doesn't
// import it or imports it blank. dot is the import spec when f dot-imports
// path, which the caller reports: the scan matches a qualifier against the
// name and has no qualifier to match once the name is gone.
func importName(f *ast.File, path string) (name string, dot *ast.ImportSpec) {
	for _, im := range f.Imports {
		p, err := strconv.Unquote(im.Path.Value)
		if err != nil || p != path {
			continue
		}
		if im.Name == nil {
			return path[strings.LastIndex(path, "/")+1:], nil
		}
		switch im.Name.Name {
		case ".":
			return "", im
		case "_":
			return "", nil
		}
		return im.Name.Name, nil
	}
	return "", nil
}

// importPath returns the path bound to name in f, empty when there is none.
func importPath(f *ast.File, name string) string {
	for _, im := range f.Imports {
		p, err := strconv.Unquote(im.Path.Value)
		if err != nil {
			continue
		}
		bound := p[strings.LastIndex(p, "/")+1:]
		if im.Name != nil {
			bound = im.Name.Name
		}
		if bound == name {
			return p
		}
	}
	return ""
}

// isGenerated reports whether f carries the datapages generated header.
func isGenerated(f *ast.File) bool {
	for _, cg := range f.Comments {
		for _, c := range cg.List {
			if c.Text == GeneratedHeader {
				return true
			}
		}
		if cg.Pos() > f.Package {
			break // Past the package clause, the header is not there.
		}
	}
	return false
}

// declaresType reports whether f declares a type of the given name.
func declaresType(f *ast.File, name string) bool {
	for _, d := range f.Decls {
		g, ok := d.(*ast.GenDecl)
		if !ok || g.Tok != token.TYPE {
			continue
		}
		for _, s := range g.Specs {
			if ts, ok := s.(*ast.TypeSpec); ok && ts.Name.Name == name {
				return true
			}
		}
	}
	return false
}

// exprString renders an expression the scan does not otherwise understand,
// such as the struct{} an application without its own session data names.
func exprString(e ast.Expr) string {
	var b strings.Builder
	if err := printer.Fprint(&b, token.NewFileSet(), e); err != nil {
		return "?"
	}
	return b.String()
}

// relTo makes a position's filename relative to root.
func relTo(root string, p token.Position) token.Position {
	if rel, err := filepath.Rel(root, p.Filename); err == nil {
		p.Filename = rel
	}
	return p
}
